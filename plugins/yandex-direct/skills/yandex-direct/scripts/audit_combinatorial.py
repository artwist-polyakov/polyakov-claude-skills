def campaign_batches(campaign_ids, limits) -> list:
    """Кампании порциями под предел `Ads.get.CampaignIds` — их не больше десяти.

    Негодный предел отдаётся `objects.fits_selection` целой порцией: отвергает
    он, и текст отказа один. Второе место, отвергающее то же самое, разошлось
    бы с ним в формулировке, а формулировка здесь и есть весь ответ."""
    ordered = sorted(dict.fromkeys(int(one) for one in campaign_ids))
    top = limits.selection(objects.SERVICE_ADS, "CampaignIds")
    if not isinstance(top, int) or isinstance(top, bool) or top < 1:
        return [ordered]
    return [ordered[at:at + top] for at in range(0, len(ordered), top)]


