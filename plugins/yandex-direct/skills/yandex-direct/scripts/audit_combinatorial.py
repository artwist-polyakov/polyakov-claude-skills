def _structures() -> tuple:
    """Структура после переноса и структура до него — из `objects`.

    Перечень берётся у `objects.KIT_STRUCTURES`, а не повторяется:
    «структуры, у которых комплект бывает» и «структуры, между которыми идёт
    перенос» — одно и то же множество, и разойдясь, они разошлись бы молча."""
    other = [name for name in objects.KIT_STRUCTURES if name != objects.RESPONSIVE]
    if len(objects.KIT_STRUCTURES) != 2 or len(other) != 1:
        raise DirectFailure(
            f"Структур комплекта стало {len(objects.KIT_STRUCTURES)} "
            f"({', '.join(objects.KIT_STRUCTURES) or 'ни одной'}), а аудит "
            f"конвертации считает переход между двумя. Доли, которые он "
            f"печатает, при третьей структуре складываться перестают."
        )
    return objects.RESPONSIVE, other[0]


AFTER, BEFORE = _structures()


