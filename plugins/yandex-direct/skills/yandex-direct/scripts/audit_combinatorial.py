def tally(rows: list) -> dict:
    """Всё, что аудит утверждает про выборку, одним разбором.

    Знаменатель доли — объявления, у которых комплект **бывает**. Медийный
    баннер и товарное объявление в него не входят: семи заголовков у них нет
    по устройству, и «перенос впереди» про них — не наблюдение, а
    бессмыслица."""
    kit = [row for row in rows if row["kit_applies"]]
    live = [row for row in kit if not row["archived"]]
    combo = [row for row in kit if row["format"] == COMBINATORIAL]
    ahead = [row for row in kit if row["format"] == TEXT]
    short_kits = [row for row in combo if row["complete"] is False]
    return {
        "ads": len(rows),
        "kit": len(kit),
        "live": len(live),
        "archived": len(kit) - len(live),
        "combinatorial": combo,
        "text": ahead,
        "incomplete": short_kits,
        "merged": [row for row in combo if row["merged_title"]],
        # Единственный заголовок без следа слияния. Утверждать потерю нельзя:
        # второго заголовка могло не быть вовсе.
        "single_title": [row for row in combo
                         if row["titles"] == 1 and not row["merged_title"]],
        "will_lose": [row for row in ahead if row["title2_survives"] is False],
        "will_keep": [row for row in ahead if row["title2_survives"] is True],
        # Снапшот советуется по **кампании**: перенос идёт в два этапа, и
        # второй — архивные кампании. Объявление, живое внутри архивной
        # кампании, времени имеет столько же, сколько архивное, и отбор по
        # состоянию объявления его терял.
        "will_lose_archived": [row for row in ahead
                               if row["title2_survives"] is False
                               and row["campaign_archived"]],
        # Своё состояние объявления — отдельным числом: оно про то, показывается
        # ли объявление, а не про то, сколько у него времени до переноса.
        "will_lose_archived_ad": [row for row in ahead
                                  if row["title2_survives"] is False
                                  and row["archived"]],
        "unclear": [row for row in kit if row["rejected_elements"]],
        # По видам, а не одним числом: человеку, которому корзину отдают на
        # разбор, «отклонено 14» не говорит, чинить заголовки или картинки.
        "rejected_kinds": {
            said: sum(1 for row in kit for item in row["rejected"]
                      if item["part"] == part)
            for part, said in (("titles", "заголовков"), ("texts", "текстов"),
                               ("images", "изображений"), ("videos", "видео"),
                               ("carousel", "карусель"))
        },
        "carousel": [row for row in kit if row["rejected_carousel"]],
        "missing_titles": sum(row["missing_titles"] or 0 for row in short_kits),
        "missing_texts": sum(row["missing_texts"] or 0 for row in short_kits),
    }


def share(part: int, whole: int) -> str:
    """Доля процентами. Пустой знаменатель — прочерк, а не ноль процентов."""
    return "—" if not whole else f"{part * 100 // whole} %"


def total_cost(rows: list, spent: bool = True):
    """Сумма расхода по строкам. `None` означает «неизвестно».

    Складываются только известные суммы: объявление без строки в отчёте
    расхода не имеет **неизвестного**, а не нулевого, и подменять одно другим
    значило бы занизить масштаб ровно там, где отчёт промолчал.

    Пустое множество — другое дело, и это не придирка. Когда расход снят, а
    недозаполненных объявлений нет вовсе, их суммарный расход равен нулю
    **точно**: складывать нечего, но и неизвестного нет. `None` на этом месте
    говорил бы «расход неизвестен» про множество, которого не существует, — и
    охват рядом при этом объявлен полным.

    Отсюда же следует, что сама сумма без охвата ничего не значит, — см.
    `coverage`. Отдавать её одну значит выдавать оценку снизу за итог."""
    if not spent:
        return None
    if not rows:
        return 0
    known = [int(row["cost"]) for row in rows if row["cost"]]
    return sum(known) if known else None


def coverage(rows: list) -> dict:
    """Скольким объявлениям сумма вообще известна.

    Полный отчёт покрывает не всякую выборку: строк по объявлению, у которого
    за период не было показов, в нём нет вовсе. Аудит эту разницу уже держит —
    расход такого объявления «неизвестен», а не ноль, — но **сумма** её
    теряла: складывались известные, а подписывалось итогом.

    Признак поэтому свой, отдельный от полноты отчёта. Полнота говорит, всё ли
    Директ отдал; охват — по скольким из спрошенных объявлений он что-то
    сказал. Обрезанный отчёт с полным охватом и целый отчёт с половинным
    охватом — разные исходы, и один признак на оба врал бы про каждый второй."""
    counted = [row for row in rows if row["cost"]]
    return {"ads": len(rows), "with_cost": len(counted),
            "complete": len(counted) == len(rows)}


def account_currency(accounts, login: str) -> str:
    """Валюта, которой подписан расход, — **кабинетная**, а не кампанийная.

    Столбца с валютой в отчёте нет, и параметра, задающего её, тоже нет:
    суммы приходят в валюте рекламодателя, а называет её `Clients.get`
    полем `Currency` (`REPORTS.md`, раздел 10). Перечень кабинетов её оттуда
    и читает, поэтому спрашивать заново нечего.

    Кампанийная `Currency` подписывает деньги кампании — остаток, бюджет,
    ставки, — и расходу отчёта не тождественна. У кампании условных единиц
    там стоит `YND_FIXED`: валютой рекламодателя это значение не бывает
    вовсе, и расход в текущей валюте оказался бы подписан условной. Обход по
    кабинету портился иначе и тише: кампании со `YND_FIXED` рядом с обычными
    давали два значения, общего не находилось, и подпись пропадала у всего
    ответа — при том что валюта у кабинета ровно одна.

    Так же берут её соседи, считающие в валюте кабинета: `bids.py` — перед
    сверкой границ ставки, `report.py` — на каждую строку отчёта, потому что
    отчёт с фильтром по `ClientLogin` сводит кабинеты одной таблицей.

    Пусто значит «назвать нечем», и причин тому две: кабинета может не быть в
    перечне — логин берётся и из настройки тоже, — а может не быть валюты у
    самого кабинета, если Директ поля не назвал. Обе кончаются одинаково:
    суммы показываются без подписи, а не подписываются догадкой."""
    cabinet = accounts.by_login(login)
    return cabinet.currency if cabinet is not None else ""


def account_vat(accounts, login: str):
    """Ставка НДС кабинета. `None` — «Директ её не назвал».

    Приходит вместе с перечнем кабинетов: имя `VatRate` принимают оба метода
    перечня (`REPORTS.md`, раздел 10), и хранится ставка там же. Пустое
    значение здесь не ноль процентов — поле объявлено `nillable`, и ноль на
    его месте объяснял бы расхождение с интерфейсом ставкой, которой кабинет
    не сообщал."""
    cabinet = accounts.by_login(login)
    return None if cabinet is None else cabinet.vat_rate


def vat_said(included, rate, since: str = "") -> str:
    """Учёт НДС и ставка — рядом с цифрами, а не в памяти человека.

    Отчёт, про который неизвестно, с НДС он или без и по какой ставке,
    сравнивать не с чем: замер справочника даёт отношение ровно 1,22 между
    теми же сутками с `IncludeVAT: YES` и `NO`, а интерфейс кабинета
    показывает статистику без налога. Ранжирование от этого не меняется —
    множитель общий, — но суммы читают как деньги, и именно они уезжают в
    файл, в `--json` и в спутник выгрузки.

    Дата перечня кабинетов идёт рядом со ставкой: слой у перечня вечный,
    ставки меняются, и устаревание должно быть видно, а не подразумеваться."""
    counted = "учтён" if included else "не учтён"
    if rate is None:
        return f"НДС {counted} · ставка кабинета не названа"
    age = f", список от {since[:10]}" if since else ""
    return f"НДС {counted} · ставка {rate:g} %{age}"


def money_text(amount, currency: str) -> str:
    if amount is None:
        return "неизвестен"
    try:
        return money.format_api(int(amount), currency)
    except (money.MoneyError, ValueError):
        return str(amount)


def artifact_name(campaign_id, chosen: dict, spent: bool,
                  window: str = "") -> str:
    """Имя записи с полными данными — по тому, **что** аудитировали.

    Одного логина мало, и это не про параллельные запуски. Подвал сводки
    называет файл, и человек открывает его позже — иногда сильно позже. Пока
    имя зависело только от кабинета, обход по кабинету и разбор одной кампании
    писали в один файл: путь из первой сводки после второго запуска указывал на
    чужую выборку, ничем себя не выдавая.

    В подпись входит всё, что меняет **содержимое**: отбор, период и то,
    снимался ли расход. Кабинет в подпись не входит — он уже каталог записи.

    «Снимался» здесь означает **снят**, а не «его просили». Расход не
    снимается и без `--no-spend` — отчёт отказывает, — и подпись по просьбе
    свела бы такой запуск с удачным под одним именем, когда окна нет у обоих.

    Отбор берётся **разрешённым**, а не тем, что человек набрал. Аргумент
    `--campaign` принимает и кусок названия, и один и тот же кусок со временем
    попадает в другую кампанию: соседнюю переименовали, и единственным
    совпадением стала она. Подпись по набранному тексту записала бы её аудит
    поверх прежнего под тем же именем — то есть ровно тот исход, ради которого
    подпись и заводилась, только через название вместо кабинета.

    То же и с периодом, и по той же причине. Имя `LAST_30_DAYS` переезжает
    каждую ночь: назавтра это другие тридцать дней, другой расход и другое
    ранжирование, а подпись по имени оставила бы одно место на оба. Поэтому в
    неё идёт **разрешённое окно**, когда отчёт его назвал. Не назвал или расход
    не снимался — в подписи остаётся одно имя: выдумывать окно, которого
    Директ не сообщил, значило бы разводить записи по признаку, которого нет.

    Обход по кабинету при этом отбора не имеет, и перечня кампаний в подпись не
    кладётся: он менялся бы при каждой заведённой кампании, и путь к «аудиту
    кабинета» переставал бы быть одним путём."""
    return "audit-combinatorial-" + signature({
        "campaign": "" if campaign_id is None else str(campaign_id),
        "period": chosen,
        "window": window or "",
        "spend": bool(spent),
    })


def meta_beside(export: Path) -> Path:
    """Спутник выгрузки: тот же путь плюс `.meta.json`.

    Имя считается в одном месте, потому что называют его двое — тот, кто
    пишет файл, и сводка, которая говорит человеку, где он лежит. Две копии
    правила разошлись бы, и разошлись бы молча: файл лёг бы рядом, а в сводке
    стоял бы путь, по которому его нет."""
    return export.with_name(export.name + ".meta.json")


def cost_of(row: dict):
    """Расход строки целым. `None` — расход неизвестен, а не равен нулю.

    Целым, а не `Decimal`: суммируются они точно и без границы точности."""
    return int(row["cost"]) if row["cost"] else None


def ad_line(row: dict, currency: str, spent: bool) -> str:
    """Строка объявления в перечне: чем оно опознаётся и чего ему не хватает."""
    parts = [f"  {row['id']:<20}"]
    if spent:
        parts.append(f"{money_text(cost_of(row), currency):>16}")
    said = f"{row['titles']}×{row['texts']}"
    if row["missing_titles"] or row["missing_texts"]:
        lack = []
        if row["missing_titles"]:
            lack.append(plural(row["missing_titles"], "заголовка", "заголовков",
                               "заголовков"))
        if row["missing_texts"]:
            lack.append(plural(row["missing_texts"], "текста", "текстов",
                               "текстов"))
        said += " · нет " + " и ".join(lack)
    parts.append(said)
    return "  ".join(parts)


def ranked(rows: list, spent: bool) -> list:
    """Объявления по убыванию расхода, а при неизвестном расходе — по дырам."""
    if spent:
        # Объявление без строки в отчёте становится последним, а не нулевым:
        # неизвестный расход и нулевой различаются, и в порядке — тоже.
        return sorted(rows, key=lambda row: (cost_of(row) is None,
                                             -(cost_of(row) or 0),
                                             row["id"] or 0))
    return sorted(rows, key=lambda row: (-((row["missing_titles"] or 0)
                                           + (row["missing_texts"] or 0)),
                                         row["id"] or 0))


def report(where: str, entry_age: str, found: dict, rows: list, currency: str,
           spent: bool, whole_spend: bool, period_said: str, window: str,
           calls: int, asked: int, units: int, vat: dict, export=None,
           notes=(), path=None) -> None:
    """Сводка аудита. Порядок разделов — от масштаба к тому, что с ним делать."""
    # Происхождение — своей строкой, а не хвостом шапки. В шапке лежит
    # название кампании, которое человек пишет сам: длинное имя дотягивало
    # строку до предела, и срезалось при этом ровно происхождение.
    lines = [where, f"Прочитано: {entry_age}"]
    lines.append(
        f"Объявлений {found['ads']} · комплект бывает у {found['kit']} "
        f"({found['live']} неархивных) · уже комбинаторных "
        f"{len(found['combinatorial'])} "
        f"({share(len(found['combinatorial']), found['kit'])}), "
        f"ещё текстово-графических {len(found['text'])}")
    lines.append("Это доля формата, а не переноса: комбинаторным объявление "
                 "бывает и потому, что его таким создали, а истории версий "
                 "API не хранит.")
    lines.append("Читалось всеми наборами полей сразу: Titles живёт в "
                 "ResponsiveAdFieldNames, Title2 — в TextAdFieldNames.")
    lines.append("")

    incomplete = found["incomplete"]
    lines.append(
        f"Недозаполненный комплект: {len(incomplete)} из "
        f"{len(found['combinatorial'])} комбинаторных · не хватает "
        f"{plural(found['missing_titles'], 'заголовка', 'заголовков', 'заголовков')} "
        f"и {plural(found['missing_texts'], 'текста', 'текстов', 'текстов')}")
    order = ranked(incomplete, spent)
    for row in order[:SHOWN]:
        lines.append(ad_line(row, currency, spent))
    if len(order) > SHOWN:
        lines.append(f"  … ещё {len(order) - SHOWN} — в файле ниже или через "
                     f"grep по TSV рядом с ним")
    lines.append("  Порядок: " + ("по расходу за " + period_said if spent
                                  else "по числу пустых мест — расход не снимался"))
    lines.append("  Недозаполненность — наблюдение, а не приговор: комплект из "
                 "трёх сильных заголовков бывает собран осознанно.")

    lines.append("")
    single = len(found["merged"]) + len(found["single_title"])
    lines.append(
        f"Слияние Title2: из {single} комбинаторных с единственным заголовком "
        f"след слияния есть у {len(found['merged'])}, у "
        f"{len(found['single_title'])} следа нет.")
    # Историй три, а не две. Третью — «объявление создали комбинаторным с одним
    # заголовком» — добавило ревью: без неё разреженное объявление, которое
    # таким и задумывали, попадало в потери от переноса.
    lines.append("  Причин три, и состоянием они не различаются: перенос "
                 "забрал Title2, его не было у исходного объявления, "
                 "объявление сразу собрали одним заголовком.")

    ahead = found["text"]
    # Три числа, а не два: у объявления без дополнительного заголовка терять
    # нечего, и молчание о нём читалось бы как недостача в сумме.
    nothing = len(ahead) - len(found["will_lose"]) - len(found["will_keep"])
    lines.append(
        f"Перенос ещё впереди у {len(ahead)}: Title2 потеряют "
        f"{len(found['will_lose'])}, переживут перенос {len(found['will_keep'])}, "
        f"терять нечего у {nothing} — склейка длиннее "
        f"{responsive.MERGED_TITLE_LIMIT} символов теряется.")
    if found["will_lose_archived"]:
        lines.append(
            f"  Из них в архивных кампаниях {len(found['will_lose_archived'])} "
            f"— снимайте снапшот сейчас: перенос идёт в два этапа, архивные "
            f"кампании во втором, и после него точного источника не останется.")

    if found["unclear"]:
        kinds = ", ".join(f"{said} {count}" for said, count
                          in sorted(found["rejected_kinds"].items()) if count)
        lines.append(
            f"Неопределённо: "
            f"{plural(len(found['unclear']), 'объявление', 'объявления', 'объявлений')}"
            f" с отклонёнными элементами" + (f" ({kinds})" if kinds else "")
            + ". В недозаполненность они не идут.")
        # Обе половины правила, а не одна. Категоричное «показы предыдущей
        # версии продолжаются» верно лишь в первом случае из двух: у версии,
        # допущенной автоматически и затем отклонённой, показы уже не
        # возобновляются — и это настоящая остановка. По одному лишь статусу
        # они не различаются, поэтому сказать можно только «может».
        lines.append("  Прежний комплект при этом может показываться, а может "
                     "и нет: по одному статусу настоящая остановка от ложной "
                     "тревоги не отличается.")
        lines.append("  Место, значение и причина отказа — в файле ниже и в "
                     "выгрузке; разбирает человек.")
    if found["carousel"]:
        lines.append(
            f"  Карусель: {len(found['carousel'])} — только хендофф, поля "
            f"записи у карусели нет ни в ResponsiveAdAdd, ни в ResponsiveAdUpdate.")

    if spent:
        whole = total_cost([row for row in rows if row["kit_applies"]], spent)
        part = total_cost(incomplete, spent)
        # Молчащие объявления называются числом рядом с суммой. Без него сумма
        # читается как весь расход дырявых комплектов, а она — расход тех из
        # них, о ком отчёт что-то сказал.
        silent = sum(1 for row in incomplete if cost_of(row) is None)
        # «Не меньше» — не осторожность, а другое утверждение. Оценкой снизу
        # сумма становится по двум разным причинам: обрыв склейки (Директ
        # отдал не всё) и неполный охват (Директ отдал всё, но по части
        # объявлений строк нет вовсе). Напечатать её итогом хотя бы в одном из
        # этих случаев значит выдать часть расхода за весь.
        covered = coverage([row for row in rows if row["kit_applies"]])
        floor = ("" if whole_spend and covered["complete"]
                 else " (оценка снизу)")
        # Пустое окно — не повод промолчать. Отчёт за переезжающий период без
        # разрешённых дат ровно так же не привязывается к окну, и умолчание
        # возвращает ту самую двусмысленность, ради которой окно и понадобилось.
        said_window = window or "окно отчёт не назвал"
        lines.append(
            f"Расход за {period_said} ({said_window}){floor}: у недозаполненных "
            f"{money_text(part, currency)} из {money_text(whole, currency)}"
            + (f"; ещё у {silent} расход неизвестен — строки в отчёте нет, а "
               f"это не ноль." if silent else "."))
        lines.append(f"  {vat_said(vat['included'], vat['rate'], vat['listed_at'])}")
        lines.append("  Гранулярность отчётов — объявление; какой именно "
                     "элемент слабый, API не скажет (хендофф H-03).")
    lines.extend(notes)
    # Порции, а не вызовы: порция, попавшая в кэш, сети не стоила, и «читались
    # одним вызовом Ads.get» рядом с «всё пришло из кэша» противоречили друг
    # другу в одной строке. Сколько ушло в сеть, видно по возрастам.
    #
    # Баллы — цена **команды**, а не одного чтения объявлений. Своего счётчика
    # у метода нет, а общий включает и перечень кабинетов, и срез кампаний, и
    # отчёт: приписав его `Ads.get`, сводка называла бы чужую цену своей.
    lines.append(
        f"Объявления читались {plural(calls, 'порцией', 'порциями', 'порциями')} "
        f"по кампаниям — кампаний в одной не больше, чем позволяет справочник; "
        + ("все пришли из кэша." if not asked
           else f"в Ads.get ушло {asked} из них."))
    # Ноль баллов — не «в сеть не ходили». За отчёты Директ баллов не
    # сообщает вовсе: сервиса `Reports` нет в таблице стоимости методов, и
    # заголовка `Units` среди его заголовков ответа тоже нет (`REPORTS.md`,
    # раздел 1). Отчёт, снятый заново, оставляет счётчик нулевым, и «всё
    # нашлось в кэше» рядом с этим нулём было утверждением про сеть, которого
    # счётчик не подтверждает. Откуда что пришло, говорит строка происхождения
    # выше — она читает записи, а не счётчик.
    lines.append(
        f"  Команда списала {campaign_command.units_said(units)} — за всё "
        f"чтение, а не за одни объявления." if units
        else "  Баллов не списано. Про отчёт это не значит «не ходили»: "
             "за отчёты Директ баллов не сообщает.")
    lines.extend(campaign_command.export_line(export))
    if export is not None:
        lines.append(f"  Рядом — {short(meta_beside(export))}: период, валюта, "
                     f"учёт НДС и ставка, полнота и охват сумм, происхождение. "
                     f"По одним строкам выгрузки оценку снизу от итога не "
                     f"отличить.")
    outline(lines, path=path, total=len(rows))


def captured_said(epoch) -> str:
    """Когда собран этот ответ — той же записью, что и метка кэша.

    Запись перезаписывается по своему ключу: повторный аудит того же отбора за
    тот же период кладёт новый срез на место прежнего, как и всякая запись
    кэша в этом скилле (`ads.py`, `campaigns.py`, `campaign_dump.py` — все
    именуют артефакт по тому, **что** в нём, а не когда он снят). Иначе кэш
    рос бы без предела, а слой перестал бы быть кэшем.

    Поэтому файл обязан датировать **себя**: путь из вчерашней сводки
    указывает на сегодняшний срез, и различить их можно только по метке
    внутри. Метка кэша лежит в спутнике записи, а `--json` и спутник выгрузки
    его не получают вовсе."""
    return time.strftime("%Y-%m-%dT%H:%M:%S%z", time.localtime(epoch))


def as_json(login: str, where: str, found: dict, rows: list, currency: str,
            spent: bool, whole_spend: bool, provenance: dict, period_said: str,
            vat: dict, captured: str, export=None, notes=()) -> dict:
    """Ответ аудита целиком — **один** срез на все каналы.

    Собирается один раз и уходит и в `--json`, и в файл с полными данными.
    Порознь они уже расходились: файл нёс `spend_read: true` и частичные суммы
    **без** признака полноты, то есть выглядел итогом там, где лежала оценка
    снизу. Перечень полей, набранный руками во втором месте, всегда отстаёт от
    первого — и отстаёт молча, потому что оба ответа успешны.

    Строки — все, без предела показа. Предела здесь нет намеренно, в отличие от
    `ads.py`: аудит для того и написан, чтобы сводить весь кабинет, и
    обрезанный машиночитаемый ответ выдавал бы часть за целое ровно тому, кто
    читает его кодом."""
    whole = total_cost([row for row in rows if row["kit_applies"]], spent)
    return {
        "account": login,
        # Когда собран этот срез. Запись перезаписывается по своему ключу —
        # повторный аудит того же отбора кладёт новый срез на место прежнего,
        # — и путь из вчерашней сводки указывает на сегодняшние данные.
        # Различить их можно только меткой внутри самого ответа.
        "captured_at": captured,
        "selection": where,
        "period": period_said,
        # Какие дни Директ взял на самом деле. Имя периода переезжает каждую
        # ночь, и по нему одному расход к окну не привязать.
        "period_resolved": ((provenance.get("spend") or {}).get("period") or ""),
        "currency": currency,
        # Учтён ли налог в суммах и по какой ставке. Без этого сравнивать
        # отчёт не с чем: те же сутки с `IncludeVAT: YES` и `NO` расходятся
        # ровно в 1,22, а интерфейс кабинета показывает статистику без налога.
        # `null` в учёте — расход не снимался; `null` в ставке — Директ её не
        # назвал, и это не ноль процентов.
        "vat_included": vat["included"],
        "vat_rate": vat["rate"],
        # Когда снят перечень кабинетов, из которого взята ставка. Слой у него
        # вечный, а ставки меняются.
        "cabinets_listed_at": vat["listed_at"],
        "spend_read": spent,
        # Полон ли отчёт расхода. Ложь означает, что суммы ниже — оценка
        # снизу: читающий их кодом иначе примет часть за целое, а по самим
        # числам это неотличимо.
        "spend_complete": spent and whole_spend,
        # Откуда пришло **всё**, чем аудит отвечает: перечень кампаний решает
        # охват, объявления — комплекты, отчёт — ранжирование. Три источника с
        # тремя сроками, и один общий «свежо» скрыл бы, что расход снят раньше
        # остального.
        "provenance": provenance,
        "notes": list(notes),
        "counts": {
            "ads": found["ads"],
            "with_kit": found["kit"],
            "live": found["live"],
            "archived": found["archived"],
            "combinatorial": len(found["combinatorial"]),
            "text": len(found["text"]),
            "incomplete": len(found["incomplete"]),
            "merged": len(found["merged"]),
            "single_title": len(found["single_title"]),
            "will_lose_title2": len(found["will_lose"]),
            "will_keep_title2": len(found["will_keep"]),
            "will_lose_title2_archived_campaign": len(found["will_lose_archived"]),
            "will_lose_title2_archived_ad": len(found["will_lose_archived_ad"]),
            "unclear": len(found["unclear"]),
            "rejected_carousel": len(found["carousel"]),
            "missing_titles": found["missing_titles"],
            "missing_texts": found["missing_texts"],
        },
        "merged_title_limit": responsive.MERGED_TITLE_LIMIT,
        "cost_total": None if whole is None else str(whole),
        "cost_incomplete": (None if total_cost(found["incomplete"], spent) is None
                            else str(total_cost(found["incomplete"], spent))),
        # Охват каждой суммы — рядом с ней самой. По числу полнота неотличима:
        # сумма по половине объявлений выглядит суммой, и «итог» без охвата
        # читается как итог.
        "cost_coverage": coverage([row for row in rows if row["kit_applies"]]),
        "cost_incomplete_coverage": coverage(found["incomplete"]),
        "csv": None if export is None else str(export),
        "ads": ranked(rows, spent),
    }


