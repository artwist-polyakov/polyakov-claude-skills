def nothing_found(said: str, narrowed: bool) -> DirectFailure:
    """Отказ, утверждающий, что чего-то нет, — всегда с оговоркой про охват.

    Отдельная функция, а не текст на месте: таких отказов два, стоят они в
    разных ветках `main` и оба **раньше** того места, где собираются
    примечания. Дописать оговорку в один и забыть про другой — ровно то, что
    здесь уже случилось: отказ «объявлений нет» уходил без неё.

    При отборе по названной кампании оговорка не нужна: охват задан именем, и
    кампании Мастера в него не входили бы и при полном перечне."""
    return DirectFailure(said if narrowed else f"{said} {COVERAGE}")


def trusted(cache: Cache, entry, name: str, produce, said: str):
    """Запись кэша, которой можно верить: пустая на попадании перечитывается.

    Правило одно на **все** перечни, которые аудит читает через кэш, и в этом
    вся суть. Пустая запись единственная, чью правдивость нельзя отличить от
    устаревания: у непустого перечня объект хотя бы один есть, и отсутствие
    нужного ищется поиском по нему, а пустой одинаково означает и «ничего
    нет», и «ничего не было полчаса назад». Внутри срока жизни записи
    заведённый объект остаётся непрочитанным целиком.

    Перечитывается **один раз** и только на попадании: свежая пустота — это
    ответ Директа, а не возраст записи, и второй вызов ничего к нему не
    добавит.

    Перечней таких два — кампании и объявления, — и каждый закрывался
    отдельно: сперва поиск кампании по имени, потом обход по кабинету, потом
    объявления. Общее правило заведено затем, чтобы третий не пришлось искать
    ревью. Отчёт расхода под него не подпадает: пустой отчёт — это ответ про
    статистику, а не про существование объектов, и аудит уже говорит, что
    расход по такому объявлению неизвестен, а не равен нулю."""
    if entry.data or not entry.hit:
        return entry
    warn(f"{said} из кэша пуст ({human_age(entry.age)}) — перечитываю: за это "
         f"время объект могли завести.")
    cache.forget(name)
    return produce()


def trusted_slice(cache: Cache, client, accounts, login: str, entry):
    """Срез кампаний, которому можно верить. Правило общее — см. `trusted`."""
    return trusted(cache, entry, SLICE,
                   lambda: campaign_command.read_slice(cache, client, accounts,
                                                       login),
                   "Перечень кампаний")


def looks_like_id(query: str) -> bool:
    """Назван идентификатор, а не кусок названия.

    Тот же разбор, что у `campaigns.one_campaign`: `isascii` рядом с `isdigit`
    потому, что второй истинен для «²» и цифр других письменностей, из которых
    `int()` берёт не все. Своя копия правила здесь не заводится — она решала бы
    про тот же аргумент иначе, чем поиск, и расходилась бы молча."""
    wanted = str(query).strip()
    return wanted.isascii() and wanted.isdigit()


def named_campaign(cache: Cache, client, accounts, login: str, entry, query: str):
    """Кампания по имени или идентификатору. Возвращает `(кампания, срез)`.

    Не найдя кампанию в срезе из кэша, **перечитывает срез и пробует ещё раз**.
    Иначе кампания, заведённая после того, как срез лёг в кэш, объявляется
    отсутствующей в кабинете — а совет из отказа, «та же команда без
    --campaign», приводит к тому же устаревшему срезу. Отказ при этом выглядит
    ответом про кабинет, хотя он про запись в кэше.

    Перечитывание идёт и на неоднозначности, хотя помочь там не может: свежий
    срез добавляет совпадения, а не убирает. Различать два отказа по тексту
    сообщения значило бы читать чужую формулировку как признак, а различать по
    своему разбору — завести вторую копию правила отбора рядом с
    `campaigns.one_campaign`. Цена ошибки здесь — один вызов на редком случае;
    цена второй копии — расхождение, которое молчит.

    Свежий срез кладётся в кэш, а не читается мимо него: следующая команда
    получит его же, и заплачено будет один раз.

    ## Кусок названия перечитывает срез **до** поиска, а не после отказа

    Отказ — не единственный способ ошибиться на устаревшем срезе. Кусок
    названия, у которого в кэше ровно одно совпадение, мог получить второе:
    кампанию завели после того, как срез лёг. Живой отбор стал неоднозначным, а
    поиск по кэшу этого не видит и молча берёт прежнюю — то есть аудит уходит
    считать **не ту** кампанию, отчитываясь успехом.

    Идентификатор от этого свободен: он совпадает с одной кампанией и не
    становится неоднозначным оттого, что рядом завели соседнюю. Быстрый путь
    поэтому остаётся ему, и совет из отказа «назовите идентификатор» получает
    ещё одно основание."""
    def look(records, entry):
        try:
            return campaign_command.one_campaign(records, query), entry
        except DirectFailure as failure:
            # Отказ по свежему срезу — утверждение про кабинет, и оно неполно:
            # кампанию Мастера `Campaigns.get` не отдаёт ни при каком отборе,
            # поэтому «не нашлось» о ней звучит так же, как о несуществующей.
            # Человек при этом смотрит на неё в интерфейсе.
            raise DirectFailure(f"{failure} {COVERAGE_NAMED}") from None

    def afresh(said: str):
        """Перечитать срез и искать в нём. Одно место на оба повода.

        Поводов два — устаревший кусок названия и не нашедшийся отбор, — и
        порознь они уже расходились бы: копия, которую не убивает мутация,
        маскирует правку в соседней."""
        warn(f"{said} ({human_age(entry.age)}) — перечитываю перечень кампаний.")
        cache.forget(SLICE)
        fresh = campaign_command.read_slice(cache, client, accounts, login)
        return look(fresh.data, fresh)

    if entry.hit and not looks_like_id(query):
        return afresh(f"Отбор по куску названия «{query}» шёл по срезу из кэша")
    try:
        return campaign_command.one_campaign(entry.data, query), entry
    except DirectFailure:
        if not entry.hit:
            return look(entry.data, entry)
        return afresh(f"Кампания «{query}» в срезе из кэша не нашлась")


def read_ads(cache: Cache, client, accounts, login: str, campaign_ids,
             limits) -> tuple:
    """Объявления названных кампаний. Возвращает `(записи, возрасты, вызовов)`.

    Читает `ads.read_ads` — тот же вызов, которым читает команда `ads.py`.
    Своего чтения здесь нет: набор полей, сторож и кэш у аудита и у команды
    обязаны быть одни, а две копии разошлись бы на первой правке — молча и
    именно в наборе полей.

    Возрасты возвращаются перечнем, а не одним числом: порции читаются
    порознь, и часть могла прийти из кэша, часть — из сети. Возраст «самой
    свежей» подписал бы вчерашние данные сегодняшним временем.

    Третьим возвращается число **порций**, а не вызовов: попавшая в кэш порция
    сети не стоила. Сколько из них ушло в `Ads.get`, видно по возрастам — у
    попадания возраст есть, у промаха его нет."""
    records: list = []
    seen = set()
    ages: list = []
    batches = campaign_batches(campaign_ids, limits)
    for batch in batches:
        params = objects.ads_params(campaign_ids=batch)

        def read(params=params):
            return ads_command.read_ads(cache, client, accounts, login, params)

        # То же правило, что и у перечня кампаний: пустая порция из кэша
        # неотличима от устаревшей. Объявление, заведённое в пределах срока
        # жизни записи, оставалось бы непрочитанным, а аудит отчитывался бы
        # «объявлений в выборке нет» — утверждением про кабинет, сделанным по
        # записи в кэше.
        entry = trusted(cache, read(), ads_command.cache_name(
            params["SelectionCriteria"]), read, "Порция объявлений")
        ages.append(entry.age if entry.hit else None)
        for record in entry.data:
            # Кампании в порциях не пересекаются, но кэш живёт дольше одной
            # команды: запись, сделанная соседним вызовом, могла попасть в две
            # порции сразу. Дубль здесь удвоил бы и долю, и расход.
            if record.get("Id") in seen:
                continue
            seen.add(record.get("Id"))
            records.append(record)
    return records, ages, len(batches)


def asked_of(ages: list) -> int:
    """Сколько порций ушло в сеть: у попадания возраст есть, у промаха его нет."""
    return sum(1 for age in ages if age is None)


def provenance_of(slice_entry, ages: list, spend) -> dict:
    """Откуда пришло каждое из трёх, чем аудит отвечает.

    Порознь, потому что отвечают за разное и стареют по-разному. Перечень
    кампаний решает, какие кампании вообще попали в обход: кампании, которой в
    срезе нет, нет и в аудите. Объявления несут комплекты. Отчёт даёт
    ранжирование — и период `LAST_30_DAYS` переезжает каждую ночь, так что
    расход из кэша описывает не те тридцать дней, что объявления, прочитанные
    сейчас.

    Один общий признак «свежо» скрыл бы ровно это: подпись «прочитано заново»
    на выборке, у которой два источника из трёх лежали в кэше.

    Возраст объявлений — по самой **старой** порции. Смешанное чтение так и
    называется смешанным: сказать «из кэша, три минуты» про выборку, половина
    которой прочитана заново, значит подписать её тем, чего с ней не было."""
    stored = [one for one in ages if one is not None]
    return {
        "campaigns": {"from_cache": bool(slice_entry.hit),
                      "age": slice_entry.age if slice_entry.hit else None},
        "ads": {"from_cache": bool(stored) and len(stored) == len(ages),
                "batches": len(ages), "batches_from_cache": len(stored),
                "age": max(stored) if stored else None},
        "spend": (None if spend is None
                  else {"from_cache": bool(spend["from_cache"]),
                        "age": spend["age"] if spend["from_cache"] else None,
                        "pages": spend["pages"],
                        "complete": spend["complete"],
                        # Пустая строка — «шапка периода не назвала», а не
                        # «период совпал с именем»: заголовок, отключающий
                        # шапку, скилл не шлёт, но ответ бывает и без неё.
                        "period": spend["period"]}),
    }


# Как называется источник и в каком роде о нём говорить. Причастие идёт рядом
# с именем, а не подставляется одно на всех: «объявления прочитан заново»
# читается как опечатка ровно там, где человек ищет, чему верить.
SOURCE_RU = {
    "campaigns": ("перечень кампаний", "прочитан", "снимался"),
    "ads": ("объявления", "прочитаны", "снимались"),
    "spend": ("расход", "прочитан", "снимался"),
}


def source_said(kind: str, part) -> str:
    """Одна треть строки происхождения. `None` — источника не было вовсе."""
    name, read, taken = SOURCE_RU[kind]
    if part is None:
        return f"{name} не {taken}"
    if not part["from_cache"]:
        if part.get("batches", 1) > 1 and part.get("batches_from_cache"):
            # Возраст называется и здесь. Порция из кэша задаёт комплекты
            # своей части выборки наравне со свежими, и «часть из кэша» без
            # срока не отличает секунды от почти истёкшего срока жизни.
            return (f"{name}: {part['batches_from_cache']} из "
                    f"{part['batches']} порций из кэша ({human_age(part['age'])}), "
                    f"остальные заново")
        return f"{name} {read} заново"
    return f"{name} из кэша, {human_age(part['age'])}"


def age_said(provenance: dict) -> str:
    """Строка происхождения: все три источника, а не один общий признак."""
    return "; ".join(source_said(kind, provenance[kind]) for kind in SOURCE_RU)


