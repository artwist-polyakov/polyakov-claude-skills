class Parser(argparse.ArgumentParser):
    """Ошибка аргументов — код 2, и без секретов в тексте."""

    def error(self, message: str):
        self.exit(2, redact(f"{self.prog}: {message}\n"))


def main(argv=None) -> int:
    # До разбора аргументов: argparse печатает негодное значение сам, и токен,
    # случайно попавший в командную строку, ушёл бы в stderr раньше, чем скилл
    # узнал бы, что это токен.
    preload_secrets()

    parser = Parser(description="Аудит последствий автоконвертации: доля "
                                "комбинаторного формата, дырявые комплекты, "
                                "судьба Title2.")
    parser.add_argument("--env", choices=("production", "test_cabinet"),
                        help="контур и набор переменных")
    parser.add_argument("--account", metavar="ЛОГИН",
                        help="логин кабинета; при отсутствии берётся активный")
    parser.add_argument("--campaign", metavar="ID|ЧАСТЬ_НАЗВАНИЯ",
                        type=incoming.campaign_selector,
                        help="одна кампания; без аргумента — весь кабинет")
    parser.add_argument("--period", metavar="ПЕРИОД", default=SPEND_PERIOD,
                        help=f"период расхода; умолчание {SPEND_PERIOD}")
    parser.add_argument("--no-spend", action="store_true",
                        help="не снимать расход: аудит посчитает всё, кроме "
                             "ранжирования по деньгам")
    parser.add_argument("--wait", type=int, default=reports_lib.WAIT_DEFAULT,
                        metavar="СЕКУНД", help="сколько ждать готовности отчёта")
    parser.add_argument("--csv", metavar="ФАЙЛ", type=Path,
                        help="выгрузить строки аудита в файл")
    parser.add_argument("--json", action="store_true",
                        help="машиночитаемый вывод")
    add_arguments(parser)
    args = parser.parse_args(argv)
    if args.wait < 0:
        parser.error("--wait: отрицательное ожидание")

    try:
        reference = reports_lib.Reference.load()
        chosen = reports_lib.period(args.period, reference)

        client = Client.from_env(profile=args.env, warn=warn)
        accounts = Accounts.load(client, warn=warn)
        login = resolve_account(accounts, client, args.account)
        cache = Cache.from_args(args, account=login, warn=warn)
        limits = campaign_command.limits()

        slice_entry = campaign_command.read_slice(cache, client, accounts, login)
        slice_entry = trusted_slice(cache, client, accounts, login, slice_entry)
        known = list(slice_entry.data)
        where = f"Кабинет {login}"
        # Валюта спрашивается у кабинета один раз и на оба пути: расход
        # приходит в валюте рекламодателя независимо от того, названа кампания
        # или нет.
        currency = account_currency(accounts, login)
        # Учёт налога знает только заказанный отчёт, поэтому «учтён» стоит
        # неизвестным, пока отчёта нет: `--no-spend` не показывает сумм, и
        # утверждать про них нечего. Ставка и дата перечня — свойства
        # кабинета, они известны и без отчёта.
        vat = {"included": None, "rate": account_vat(accounts, login),
               "listed_at": accounts.checked_at}
        chosen_id = None
        # Порядок здесь существенный. Пустота среза проверяется **после**
        # поиска по имени, а не до: `named_campaign` умеет перечитать
        # устаревший срез, и проверка, стоящая раньше, отняла бы у него эту
        # работу — кампания, заведённая после того, как пустой срез лёг в кэш,
        # получала бы отказ, не дойдя до перечитывания.
        if args.campaign:
            campaign, slice_entry = named_campaign(
                cache, client, accounts, login, slice_entry, args.campaign)
            known = [campaign]
            chosen_id = campaign.get("Id")
            row = campaign_command.row_of(campaign)
            where = (f"Кабинет {login} · кампания {row['id']} · {row['name']} · "
                     f"{row['type_ru']}")
        else:
            if not known:
                # «Кампаний нет» сказать нельзя: кампании Мастера
                # `Campaigns.get` не возвращает **ни при каком отборе** — ни
                # обходом по шести состояниям, ни запросом по собственным `Ids`
                # (замер 01.09.2026, девятнадцать кампаний в восьми кабинетах;
                # `API_OBJECTS.md`, раздел 2.1). Пустая выборка одинаково
                # объясняется и «кабинет пуст», и «в кабинете только кампании
                # Мастера», и различить их официальным API нечем.
                raise nothing_found(
                    f"`Campaigns.get` не вернул по кабинету {login} ни одной "
                    f"кампании — это не значит, что кабинет пуст.", False)
            where = f"{where} · {plural(len(known), 'кампания', 'кампании', 'кампаний')}"

        campaign_ids = [item.get("Id") for item in known if item.get("Id")]
        records, ages, calls = read_ads(cache, client, accounts, login,
                                        campaign_ids, limits)
        if not records:
            raise nothing_found(
                f"Объявлений в выборке нет — {where}. Аудит конвертации "
                f"считает объявления, а не кампании.", bool(args.campaign))

        notes = []
        if not currency:
            # Молчаливое отсутствие подписи неотличимо от «валюты нет»: числа
            # выглядят одинаково. Сказать это надо во всех каналах разом —
            # примечания едут и в сводку, и в `--json`, и в файл, и спутником
            # выгрузки.
            notes.append(
                f"Валюта кабинета {login} неизвестна — суммы ниже без "
                f"подписи. Называет её перечень кабинетов, и там её нет: "
                f"либо кабинета в перечне, либо валюты у кабинета. Перечитать "
                f"перечень — accounts.py --no-cache.")
        if not args.campaign:
            # Правило 1: то, чего официальный API не отдаёт, отдаётся человеку
            # ранбуком. Кампании Мастера в `Campaigns.get` не приходят, значит
            # обход по кабинету — обход по кампаниям, которые метод отдаёт, а
            # не по кабинету. Сказать это надо всегда: есть ли такие кампании,
            # аудит не знает по построению — их отсутствие в ответе и есть
            # единственное, что он видит.
            notes.append(COVERAGE)
        if slice_entry.hit and not args.campaign:
            # Перечень кампаний решает охват аудита целиком: кампании, которой
            # в срезе нет, нет и в обходе — ни одного её объявления не
            # прочитано. Молчать об этом нельзя: числа выглядят полными, а
            # неполон сам список того, что считали.
            #
            # Названной кампании это не касается — но не потому, что охват
            # задан именем, а потому, что `named_campaign` перечитывает срез,
            # не найдя её. Без перечитывания исключение было бы дырой: отказ
            # «кампании в кабинете нет» приходил бы на кампанию, которая есть.
            notes.append(
                f"Перечень кампаний взят из кэша ({human_age(slice_entry.age)}): "
                f"кампания, заведённая позже, в обход не попала. Свежий обход "
                f"— та же команда с --no-cache.")
        spend = None
        whole_spend = True
        if not args.no_spend:
            params = spend_params(reference, chosen,
                                  campaign_ids if args.campaign else None)
            problems = reports_lib.check(reference, params)
            if problems:
                for problem in problems:
                    warn(f"  ✗ {problem}")
                raise DirectFailure(
                    f"Запрос расхода не отправлен: "
                    f"{plural(len(problems), 'замечание', 'замечания', 'замечаний')} "
                    f"выше. Негодное имя роняет отчёт целиком, а не столбец.")
            # Замечания слоя отчётов к самому запросу: глубина хранения,
            # неявные группировки, поля с незадокументированным множителем.
            # Отказывать не за что, но и молчать нельзя: пустой отчёт за
            # период старше трёх лет неотличим от отсутствия показов.
            notes.extend(f"Отчёт расхода: {said}"
                         for said in reports_lib.notes(reference, params))
            try:
                found_spend = read_spend(cache, client, reference, params,
                                         account=login, wait=args.wait)
            except DirectFailure as failure:
                # Отчёт — половина ответа, а не весь ответ. Аудит без расхода
                # показывает тот же масштаб и не ранжирует; упасть здесь
                # значило бы не показать ничего из-за того, что не сложилась
                # приписка к уже прочитанному.
                warn(f"Расход не снят: {failure}")
                notes.append("Расход не снят — ранжирование идёт по числу "
                             "пустых мест. Причина в stderr выше.")
            else:
                spend = found_spend["by_ad"]
                whole_spend = found_spend["complete"]
                # Учёт налога — свойство **снятых** сумм, и ставится он вместе
                # с ними, а не вместе с запросом. Отказ отчёта оставлял бы
                # «учтён» при `spend_read: false`: сумм нет, а про них
                # что-то утверждается. Значение при этом берётся у самого
                # запроса, а не у настройки: умолчание живёт в справочнике
                # пресетов, и пересказанное здесь оно отставало бы молча.
                vat["included"] = params.get("IncludeVAT") == "YES"
                if found_spend["from_cache"]:
                    # Период переезжает каждую ночь, и отчёт из кэша описывает
                    # не те дни, что объявления, прочитанные сейчас. Молчать
                    # об этом нельзя: ранжирование по расходу — вывод, ради
                    # которого команду и запускают.
                    notes.append(
                        f"Расход снят не сейчас: отчёт из кэша, "
                        f"{human_age(found_spend['age'])}. Ранжирование "
                        f"описывает тот срез, а не сегодняшний.")
                if not whole_spend:
                    # Отчёт заказан по убыванию расхода, поэтому обрыв склейки
                    # срезает **дешёвый** хвост: верх ранжирования верен, а
                    # суммы — оценка снизу. Сказать это обязательно и на
                    # попадании в кэш: предупреждение `collect` звучит один раз,
                    # живьём, и на второй запуск его уже не слышно.
                    notes.append(
                        f"Отчёт расхода оборван предохранителем склейки на "
                        f"{plural(found_spend['pages'], 'странице', 'страницах', 'страницах')}: "
                        f"суммы ниже — оценка снизу, а не итог. Верх "
                        f"ранжирования верен (отчёт заказан по убыванию "
                        f"расхода), дешёвый хвост в него не попал. Сузьте "
                        f"выборку --campaign или период --period.")
        spent = spend is not None
        if spent and not spend:
            notes.append("Отчёт вернулся без строк с расходом: за этот период "
                         "по объявлениям не потрачено ничего или статистика "
                         "не сообщена.")

        # Состояния кампаний — из того же среза, по которому шёл обход. Второй
        # раз спрашивать их незачем, а брать у объявления нечего: своего поля
        # с состоянием кампании в `AdGetItem` нет.
        states = {item.get("Id"): item.get("State") for item in known}
        rows = [audit_row(record, limits, spend, states) for record in records]
        found = tally(rows)
        provenance = provenance_of(slice_entry, ages, found_spend if spent
                                   else None)
        # Один срез на все каналы: `--json` и файл с полными данными получают
        # **одно и то же** тело. Собранные порознь, они уже расходились — файл
        # нёс частичные суммы без признака полноты, — и расходились молча:
        # оба ответа успешны. Самоуказатель в файл не кладётся: файл, ссылающийся
        # сам на себя, ответа не добавляет.
        body = as_json(login, where, found, rows, currency, spent, whole_spend,
                       provenance, reports_lib.period_said(chosen), vat,
                       captured_said(cache.clock()), args.csv, notes)
        stored = cache.write(
            # Расход **снятый**, а не запрошенный. Разница видна не при
            # `--no-spend`: у отказа отчёта расход тоже не снят, а флага
            # человек не ставил. Отчёт при этом умеет не назвать окно, и тогда
            # у обоих запусков пусто и в окне, и в отборе — подписи совпадают,
            # а содержимое разное: у одного суммы и `spend_read: true`, у
            # второго ни того ни другого. Путь из первой сводки указывал бы на
            # чужие данные, ничем себя не выдавая.
            artifact_name(chosen_id, chosen, spent,
                          body["period_resolved"]),
            "structure", body,
            index=lambda kept: tsv(kept["ads"], AUDIT_COLUMNS))
        if args.csv:
            campaign_command.dump_csv(ranked(rows, spent), AUDIT_COLUMNS,
                                      args.csv)
            # Выгрузка — четвёртый канал ответа, и уносят её отдельно от всего
            # остального. Строки в ней несут `cost`, а период, валюта, полнота
            # отчёта, охват сумм и происхождение остаются здесь: открыв такой
            # файл через неделю, оценку снизу от итога не отличить.
            #
            # Метаданные идут спутником, а не колонками: значения у них общие
            # на всю выгрузку, и повторённые в каждой строке они врут о том,
            # что меняются вместе со строкой.
            sidecar = meta_beside(args.csv)
            sidecar.write_text(
                json.dumps({name: value for name, value in body.items()
                            if name != "ads"}, ensure_ascii=False, indent=1),
                encoding="utf-8")
        units = client.units.report()["spent"]

        if args.json:
            say(json.dumps(dict(body, cache=short(stored.path)),
                           ensure_ascii=False))
        else:
            report(where, age_said(provenance), found, rows, currency,
                   spent, whole_spend, reports_lib.period_said(chosen),
                   body["period_resolved"], calls, asked_of(ages), units, vat,
                   args.csv, notes, stored.path)
    except Ambiguous as failure:
        warn(str(failure))
        for match in failure.matches[:SHOWN]:
            warn(f"  {match.cabinet.login} · {match.reason}")
        return 1
    except DirectFailure as failure:
        warn(str(failure))
        return 1
    except OSError as failure:
        warn(redact(f"Не удалось записать файл: {failure}"))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
