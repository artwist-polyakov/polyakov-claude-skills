def format_of(record: dict) -> str:
    """Формат объявления сейчас — по структурам, пришедшим в ответе.

    Отвечает на вопрос «какой формат сейчас», а не «прошло ли перенос».
    Второго ответа у API нет: комбинаторным объявление бывает и потому, что
    его таким создали, и отличить это от переноса текущим состоянием нечем."""
    bodies = objects.bodies_of(record)
    if AFTER in bodies:
        return COMBINATORIAL
    if BEFORE in bodies:
        return TEXT
    return NO_KIT


def merge_trace(title: str) -> dict:
    """След слияния в единственном заголовке. Вероятность, а не факт.

    Автоконвертация склеивает `«заголовок» + «. » + «дополнительный»`, и
    разделитель — единственное, что от этой операции остаётся в состоянии
    объекта. Признак косвенный с обеих сторон: заголовок, в котором точка с
    пробелом стояли изначально, выглядит склеенным, а склейка потерянного
    `Title2` не оставляет вообще ничего.

    Разрез берётся по **первому** разделителю. Их бывает несколько — точка с
    пробелом законно стоит и внутри самого заголовка, — и который из них
    поставила конвертация, по состоянию не видно. Поэтому пара возвращается
    как догадка о том, что было до переноса, а не как восстановленные поля."""
    text = str(title or "")
    head, joiner, tail = text.partition(responsive.TITLE_JOINER)
    merged = bool(joiner) and bool(head.strip()) and bool(tail.strip())
    return {
        "merged": merged,
        "head": head if merged else "",
        "tail": tail if merged else "",
        "length": len(text),
        "separators": text.count(responsive.TITLE_JOINER),
    }


def title2_forecast(record: dict) -> dict:
    """Что перенос сделает с `Title2` текстово-графического объявления.

    Здесь предсказание точное, а не вероятностное: оба заголовка ещё лежат в
    кабинете, и вопрос сводится к длине склейки. Считает её `merged_title` из
    `responsive.py` — правило границы живёт там одно на весь скилл, и своей
    копии здесь нет намеренно: разойдясь на символ, копия предсказывала бы
    сохранным заголовок, который Директ выбросит.

    `applies` ложно, когда терять нечего: дополнительного заголовка нет, или
    объявление уже перенесено. Ноль на этом месте означал бы «потеря не
    грозит» там, где вопрос не задавался."""
    body = objects.bodies_of(record).get(BEFORE) or {}
    title = str(body.get("Title") or "")
    title2 = body.get("Title2")
    title2 = "" if title2 is None else str(title2)
    if not title or not title2:
        return {"applies": False, "title": title, "title2": title2,
                "glued": "", "glued_length": 0, "survives": None}
    glued = f"{title}{responsive.TITLE_JOINER}{title2}"
    _, remainder = responsive.merged_title(title, title2)
    return {"applies": True, "title": title, "title2": title2,
            "glued": glued, "glued_length": len(glued),
            "survives": remainder is None}


def audit_row(record: dict, limits, spend=None, states=None) -> dict:
    """Плоская строка аудита: состав комплекта, судьба `Title2`, расход.

    Плоская по той же причине, что и строки `ads.py`: по индексу ищут через
    `grep`, а вложенный объект в ячейке TSV ищется только целиком."""
    kit = objects.composition(record, limits)
    state = record.get("State") or ""
    # Состояние **кампании** — своя ось, а не то же самое, что состояние
    # объявления. Перенос идёт в два этапа, и второй этап — архивные
    # **кампании** (`API_OBJECTS.md`, раздел 2.1): объявление, живое внутри
    # архивной кампании, времени имеет ровно столько же, сколько архивное. Обе
    # оси независимы, и объявление `OFF` в архивной кампании — обычный случай,
    # а не исключение.
    campaign_state = str((states or {}).get(record.get("CampaignId")) or "")
    where = format_of(record)
    titles = kit["parts"]["titles"]
    # След слияния ищется только там, где заголовок один. У объявления с
    # семью заголовками разделитель внутри любого из них про перенос не
    # говорит ничего: комплект уже собран, и терять было нечего.
    trace = (merge_trace(titles[0]["value"])
             if where == COMBINATORIAL and len(titles) == 1
             else {"merged": False, "head": "", "tail": "", "length": 0,
                   "separators": 0})
    ahead = (title2_forecast(record) if where == TEXT
             else {"applies": False, "title": "", "title2": "", "glued": "",
                   "glued_length": 0, "survives": None})
    # Отклонённые элементы — с их местом, значением и причиной, и **по видам**.
    # Одних счётчиков мало: корзина «неопределённо» объявлена хендоффом, а
    # разобрать её человеку не по чему, если из строки не видно, заголовок
    # отклонён или картинка и что именно сказала модерация. Перечитывать ради
    # этого объявление заново значит держать в файле «полные данные», которых
    # в нём нет.
    rejected = {part: [item for item in items
                       if item["status"] == objects.REJECTED]
                for part, items in kit["parts"].items()}
    flat = [(part, item) for part, items in rejected.items() for item in items]
    money_spent = None if spend is None else spend.get(record.get("Id"))
    return {
        "id": record.get("Id"),
        "campaign_id": record.get("CampaignId"),
        "group_id": record.get("AdGroupId"),
        "type": record.get("Type") or "",
        "state": state,
        "state_ru": objects.AD_STATE_RU.get(state, state),
        "status": record.get("Status") or "",
        "clarification": record.get("StatusClarification") or "",
        "archived": state == ARCHIVED,
        "campaign_state": campaign_state,
        "campaign_archived": campaign_state == ARCHIVED,
        "format": where,
        "format_ru": FORMAT_RU[where],
        "structures": ", ".join(kit["structures"]),
        "kit_applies": kit["kit_applies"],
        "titles": kit["counts"]["titles"],
        "texts": kit["counts"]["texts"],
        "images": kit["counts"]["images"],
        "videos": kit["counts"]["videos"],
        "carousel": kit["counts"]["carousel"],
        "combinations": kit["combinations"],
        "complete": kit["complete"],
        "missing_titles": kit["missing"].get("titles"),
        "missing_texts": kit["missing"].get("texts"),
        "title": titles[0]["value"] if titles else "",
        "merged_title": trace["merged"],
        "merge_head": trace["head"],
        "merge_tail": trace["tail"],
        "title_length": trace["length"],
        "title2": ahead["title2"],
        "title2_glued_length": ahead["glued_length"],
        # Три ответа, а не два: `None` — «вопрос не задавался», и ноль или
        # ложь на его месте выдали бы за находку объявление, которому терять
        # нечего.
        "title2_survives": ahead["survives"],
        "rejected_elements": len(flat),
        "rejected_carousel": len(rejected["carousel"]),
        # Два представления одного, и оба в выгрузке. Плоское — для `grep` по
        # TSV: по месту отказа ищут глазами и командой. Структурное — для
        # разбора: в нём лежит **значение**, и без него отклонённый хэш
        # изображения из выгрузки не опознать, а сводка обещает, что опознать
        # можно. Список словарей `tsv` укладывает в одну ячейку сам, экранируя
        # перенос и табуляцию.
        "rejected_where": ", ".join(item["where"] for _, item in flat),
        "rejected": [dict(item, part=part) for part, item in flat],
        "cost": "" if money_spent is None else str(money_spent),
    }


