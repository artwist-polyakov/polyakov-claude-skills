def outline(lines, *, path=None, total=None, limit: int = STDOUT_LIMIT, out=None) -> int:
    """Сводка в stdout: не длиннее тридцати строк, с путём к полным данным.

    Считаются физические строки, а не переданные элементы: строка с переносами
    внутри — это несколько строк на экране, и предел, считающий её одной, не
    предел. Лишнее не выбрасывается молча — последняя строка говорит, сколько
    строк не показано и где лежит целое.

    Возвращает число напечатанных строк, чтобы проверке было что утверждать."""
    if limit < 2:
        raise DirectFailure(
            f"Предел вывода {limit} строк не оставляет места ни на сводку, "
            f"ни на путь к файлу."
        )
    stream = out if out is not None else sys.stdout
    body = [_plain(one) for item in lines for one in str(item).splitlines() or [""]]

    footer = []
    if path is not None:
        where = short(Path(path))
        count = "" if total is None else f"{plural(total, 'объект', 'объекта', 'объектов')}: "
        # Через ту же обработку, что и остальные строки. Путь приходит извне —
        # это может быть `--csv` от пользователя, — и «строка сводки безопасна,
        # кроме последней» не свойство, а его отсутствие.
        footer.append(_plain(f"Полные данные — {count}{where}"))

    budget = limit - len(footer)
    if len(body) > budget:
        shown = body[:budget - 1]
        hidden = len(body) - len(shown)
        body = shown + [f"… ещё {plural(hidden, 'строка', 'строки', 'строк')}"]

    for line in body + footer:
        print(line, file=stream)
    return len(body) + len(footer)


def _printable(text) -> str:
    """Одна строка ограниченной длины: без управляющих символов, но с секретами.

    Ведущие пробелы сохраняются — на них держится вложенность сводки, — а
    остальное приводится к одной строке. `ESC[2J` в названии кампании иначе
    стирает пользователю экран вместе со сводкой, а перенос строки в значении
    сдвигает столбцы индекса.

    Секреты здесь **не** вырезаются намеренно. Вырезанный токен прошёл бы
    проверку записи как чистый текст, и кэш молча сохранил бы файл, в котором
    вместо токена стоит маска, — вместо того чтобы отказаться его писать."""
    safe = "".join(
        " " if unicodedata.category(character) in BREAKING else character
        for character in str(text)
    ).rstrip()
    if len(safe) > LINE_WIDTH:
        safe = safe[:LINE_WIDTH] + "…"
    return safe


def _plain(text) -> str:
    """То же для stdout: секреты вырезаны, потому что печатать их некуда."""
    return _printable(redact(str(text)))


def plural(count: int, one: str, few: str, many: str) -> str:
    """«1 объект», «2 объекта», «5 объектов»: сводку читает человек."""
    tail, hundred = count % 10, count % 100
    if tail == 1 and hundred != 11:
        return f"{count} {one}"
    if 2 <= tail <= 4 and not 12 <= hundred <= 14:
        return f"{count} {few}"
    return f"{count} {many}"


def human_size(size: int) -> str:
    for unit, step in (("МБ", 1024 * 1024), ("КБ", 1024)):
        if size >= step:
            return f"{size / step:.1f} {unit}"
    return f"{size} Б"


def human_age(seconds: float) -> str:
    if seconds < MINUTE:
        return "только что"
    if seconds < HOUR:
        return plural(int(seconds // MINUTE), "минута", "минуты", "минут") + " назад"
    if seconds < DAY:
        return plural(int(seconds // HOUR), "час", "часа", "часов") + " назад"
    return plural(int(seconds // DAY), "сутки", "суток", "суток") + " назад"


