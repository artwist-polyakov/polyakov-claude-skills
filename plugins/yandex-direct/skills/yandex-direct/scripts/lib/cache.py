def signature(params, length: int = 16) -> str:
    """Устойчивая подпись параметров запроса — ключ слоя отчётов.

    Подписывается ровно то, что дали: по справочнику (`references/REPORTS.md`,
    раздел 9) ключ кэша скилла — хеш параметров **без** идентификатора запуска,
    и решает, что в него входит, вызывающий код."""
    text = json.dumps(
        params, ensure_ascii=False, sort_keys=True, separators=(",", ":"), default=str,
    )
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:length]


def tsv(records, columns) -> str:
    """TSV-индекс: поиск через `grep` без загрузки данных в контекст.

    Табуляция и перенос строки внутри значения заменяются пробелом. Иначе
    название кампании с переносом сдвигает столбцы, и `grep` уверенно находит
    не то — а проверить это по самому индексу уже нечем."""
    columns = list(columns)
    lines = ["\t".join(columns)]
    for record in records:
        lines.append("\t".join(_cell(_field(record, column)) for column in columns))
    return "\n".join(lines) + "\n"


def _field(record, column):
    if isinstance(record, dict):
        return record.get(column, "")
    return getattr(record, column, "")


def _cell(value) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "да" if value else "нет"
    if isinstance(value, (list, tuple)):
        return " ".join(_cell(item) for item in value)
    if isinstance(value, dict):
        # json.dumps экранирует перенос и табуляцию внутри строк, поэтому
        # вложенный объект укладывается в одну ячейку сам собой.
        return _printable(_dumps(value))
    return _printable(value)


