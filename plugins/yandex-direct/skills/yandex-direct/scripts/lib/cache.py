def add_arguments(parser) -> None:
    """Флаг `--no-cache` в едином для всех читающих скриптов виде.

    Заводится здесь, а не в каждом скрипте своими словами: одинаково
    названный, но по-разному понятый флаг хуже отсутствующего."""
    parser.add_argument(
        "--no-cache",
        action="store_true",
        help="не брать сохранённое, запросить данные заново",
    )


