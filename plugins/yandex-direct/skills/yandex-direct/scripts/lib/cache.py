def _segment(value: str, what: str, reserved: bool = False) -> str:
    """Один сегмент пути внутри кэша.

    Проверка строгая и не исправляющая: `../` не заменяется на подчёркивание, а
    отвергается. Исправленный путь тихо кладёт данные не туда, куда просили, —
    два кабинета сливаются в один, и разницы не видно до первой записи.

    Токен здесь тоже не пройдёт. Он состоит из тех же букв и цифр, что и логин,
    поэтому набранный по ошибке в `--account` он проходит проверку набора
    символов и становится **именем каталога** — секрет на диске мимо всякой
    проверки содержимого. Отказ приходит до создания чего бы то ни было.

    `reserved=True` разрешает точку в начале — и только её. Так помечается
    каталог общих записей в корне кэша: логин с точки не начинается, и
    столкновение с каталогом кабинета становится невозможным по построению.
    Занятые именами служебных файлов имена при этом отвергаются: каталог
    `.wipe.lock` не завёлся бы всё равно, но сказать об этом лучше словами,
    чем ошибкой файловой системы."""
    body = value[1:] if reserved and value.startswith(".") else value
    if not body or not SEGMENT.match(body) or body.startswith("."):
        raise DirectFailure(
            f"{what} «{excerpt(value, 64)}» не годится для имени в кэше. "
            f"Допустимы латинские буквы, цифры и знаки @ . _ -, "
            f"и имя не начинается с точки"
            + (" — кроме одной, отделяющей общий каталог от кабинета." if reserved
               else ".")
        )
    if reserved and value in (KEEP_FILE, WIPE_LOCK):
        raise DirectFailure(
            f"Имя «{value}» занято служебным файлом кэша: каталогом оно быть "
            f"не может."
        )
    if redact(value) != value:
        # Значение не показывается: жалоба на секрет, печатающая секрет, — это
        # утечка секрета.
        raise DirectFailure(
            f"{what} совпадает с токеном. Именем каталога или файла в кэше "
            f"токен не бывает — похоже, значение попало сюда по ошибке."
        )
    return value


def account_dir_name(account: str) -> str:
    """Имя каталога кабинета: логин в нижнем регистре.

    Регистр снимается не из вкуса. Файловая система macOS по умолчанию
    регистронезависима: `Romashka` и `romashka` — один каталог, но два разных
    ключа в коде, и запись легла бы в каталог с чужим именем. Логин в том
    виде, в каком его дал вызывающий код, сохраняется в метаданных записи."""
    return _segment(account, "Логин кабинета").lower()


class Cache:
    """Кэш одного кабинета.

    Одна запись — три файла:

    * `<имя>.json` — полные данные;
    * `<имя>.tsv` — индекс для поиска через `grep` без загрузки в контекст,
      если вызывающий код его дал;
    * `<имя>.meta.json` — слой, время записи, число объектов, подпись запроса.

    Метаданные лежат отдельно, снимаются **до** первой правки файлов и пишутся
    **после** последней. В промежутке записи для чтения не существует, поэтому
    оборвавшаяся перезапись даёт промах, а не смесь двух поколений: новых
    данных под прежней отметкой времени и прежнего индекса рядом с ними.
    Промах стоит одного вызова API, смесь — неверного ответа.

    Тому, кто прочитал метаданные за миг до чужой перезаписи, этого мало, и
    чтение перепроверяет их после данных — см. `read`. Двум пишущим сразу не
    помогает и перепроверка, поэтому правку держит замок на четвёртом, пустом
    файле `<имя>.lock` — см. `_exclusive`.

    Отдельный файл заодно позволяет перечислить кэш, не читая данные: команда
    просмотра открывает только метаданные, а не мегабайты выгрузок, ради
    экономии которых кэш и заведён."""

    def __init__(
        self,
        account: str = "",
        *,
        root=None,
        reuse: bool = True,
        store: bool = True,
        warn=None,
        clock=None,
    ):
        self.account = account or ""
        # Корень берётся в момент сборки, а не в момент объявления: значение по
        # умолчанию, вычисленное при импорте, невозможно подменить, и проверка
        # очистки шла бы по настоящему каталогу кэша.
        self.root = Path(root) if root is not None else CACHE_DIR
        self.reuse = reuse
        self.store = store
        self.warn = warn or warn_to_stderr
        self.clock = clock or time.time
        # Имя каталога проверяется при сборке, а не при первой записи: отказ
        # на негодном логине должен приходить до сетевых вызовов, а не после.
        self.folder = account_dir_name(self.account) if self.account else ""

    # -- режимы -------------------------------------------------------------

    @classmethod
    def bypass(cls, account: str = "", **options):
        """Чтение мимо кэша: не читает сохранённое и ничего не сохраняет."""
        options["reuse"] = False
        options["store"] = False
        return cls(account, **options)

    @classmethod
    def from_args(cls, args, account: str = "", **options):
        """Кэш по разобранным аргументам: `--no-cache` отключает чтение.

        Запись при этом остаётся: пользователь просил свежие данные, а не
        запрет сохранять их. Полный обход — `Cache.bypass`, и он не аргумент
        командной строки, потому что относится к конвейеру записи, а не к
        желанию человека."""
        options["reuse"] = not getattr(args, "no_cache", False)
        return cls(account, **options)

    @property
    def bypassed(self) -> bool:
        return not self.reuse and not self.store

    # -- пути ---------------------------------------------------------------

    @property
    def directory(self) -> Path:
        return self.root / self.folder if self.folder else self.root

    def path(self, name: str, suffix: str = ".json") -> Path:
        """Путь записи. Имя может содержать `/`: `reports/<подпись>`."""
        # Сравнение без учёта регистра: на регистронезависимой файловой
        # системе — на macOS она такая по умолчанию — данные записи
        # `campaigns.META` легли бы в файл, который и есть метаданные записи
        # `campaigns`, и первая запись перестала бы читаться.
        if name.casefold().endswith(".meta"):
            raise DirectFailure(
                f"Имя записи «{excerpt(name, 64)}» занято: файл метаданных "
                f"записи «{name[:-len('.meta')]}» назывался бы так же."
            )
        raw = name.split("/")
        # Каталог прямо в корне кэша — это кабинет, и только кабинет. Иначе
        # `Cache().path("sync/срез")` и `Cache("sync").path("срез")` — один и
        # тот же файл: кабинет с логином `sync` затирает общие слепки, а
        # `--clear --account sync` их удаляет.
        #
        # Общей записи, которой нужен свой каталог, он поэтому даётся с
        # оговоркой: имя с точки в начале. Логин с точки не начинается —
        # это и делает столкновение невозможным, а не соглашение об именах.
        # Так `A-02` кладёт слепки сверки в `cache/.sync/`.
        reserved = not self.folder and len(raw) > 1 and raw[0].startswith(".")
        parts = [_segment(part, "Имя записи", reserved=reserved and number == 0)
                 for number, part in enumerate(raw)]
        if not self.folder and len(parts) > 1 and not reserved:
            raise DirectFailure(
                f"Запись без кабинета «{excerpt(name, 64)}» завела бы каталог в "
                f"корне кэша, а каталог в корне — это кабинет. Общие записи "
                f"либо лежат в корне без вложенности, либо начинаются с точки: "
                f"«.{raw[0]}/…»."
            )
        # Расширение приписывается, а не подменяется: `with_suffix` у имени
        # `report.v2` дал бы `report.json`, и две разные записи слились бы в
        # одну, ничего об этом не сказав.
        target = self.directory.joinpath(*parts[:-1]) / (parts[-1] + suffix)
        # Проверка сегментов уже не пускает `..`, но итог сверяется ещё раз:
        # цена ошибки здесь — удаление файлов за пределами кэша.
        if not _inside(target, self.root):
            raise DirectFailure(
                f"Путь записи «{excerpt(name, 64)}» уводит за пределы "
                f"{short(self.root)}."
            )
        _no_links(target, self.root)
        return target

    # -- чтение -------------------------------------------------------------

    def read(self, name: str, layer: str, *, ttl=None):
        """Запись из кэша или `None`, если её нет, она просрочена или негодна.

        Промах — обычное дело, а не ошибка: битый или обрезанный файл тоже
        промах. Единственное, о чём при этом говорится вслух, — что файл был и
        не прочитался: молчание здесь выглядит как «кэш не работает».

        Чтение идёт по одному поколению записи целиком. Снятие метаданных перед
        правкой файлов защищает того, кто их ещё не прочитал; тот, кто прочитал
        их за миг до чужой перезаписи, без второй проверки получил бы новые
        данные под прежней отметкой времени, а рядом — прежний индекс. Поэтому
        метаданные перечитываются после данных, и запись, сменившаяся под
        чтением, читается заново. Не блокировка: замок пришлось бы снимать
        после падения, а здесь худший исход — промах."""
        limit = _ttl(layer, ttl)
        if not self.reuse:
            return None
        meta_path = self.path(name, META_SUFFIX)
        data_path = self.path(name)
        for _ in range(READ_ATTEMPTS):
            found = self._attempt(name, layer, limit, meta_path, data_path)
            if found is not _CHANGED:
                return found
        # Запись меняют прямо сейчас и не в первый раз. Промах стоит вызова
        # API, а бесконечное перечитывание — всего времени работы.
        return None

    def _attempt(self, name: str, layer: str, limit, meta_path: Path, data_path: Path):
        """Одна попытка чтения. `_CHANGED` — запись сменилась, надо заново."""
        meta = self._load(meta_path)
        # Разобрался — ещё не значит «годен»: `[]` вместо объекта разбирается,
        # а `meta.get` на нём падает. Негодная запись — промах, как и битая.
        if not isinstance(meta, dict) or not data_path.is_file():
            return None
        stored_layer = meta.get("layer")
        if stored_layer != layer:
            # Два места спорят о том, что лежит под этим именем, и у каждого
            # свой срок жизни. Промолчать значило бы отдать данные по чужому
            # сроку; сказать вслух — назвать имя, у которого два хозяина.
            self.warn(
                f"Запись кэша «{name}» сохранена слоем «{excerpt(stored_layer, 32)}», "
                f"а запрошена слоем «{layer}». Считается отсутствующей."
            )
            return None
        # Отметка времени — число из файла, поэтому через `_finite`: `NaN`
        # прошёл бы проверку типа и сделал запись вечно свежей.
        epoch = _finite(meta.get("epoch"))
        if epoch is None:
            return None
        if not isinstance(meta.get("generation"), str):
            # Записи без метки поколения этот модуль не пишет. Значит файл
            # чужой или от прежней версии — перечитать дешевле, чем гадать.
            return None
        age = self.clock() - epoch
        # У слоя без срока возраст не сравнивается ни с чем — в том числе с
        # нулём. Отвергнуть запись из будущего значило бы устаревание по
        # времени: часы, отведённые назад переводом или сверкой с сервером,
        # стоили бы полного обхода агентства, а слой заведён ровно затем,
        # чтобы за него не платить.
        if limit is not FOREVER and (age < 0 or age > limit):
            return None
        data = self._load(data_path)
        if data is None:
            return None
        index_path = _existing(self.path(name, ".tsv"))
        # Метаданные снова, уже после данных и индекса: их отсутствие или чужая
        # метка поколения означают, что прочитанное собрано из двух поколений.
        again = self._load(meta_path)
        if not isinstance(again, dict) or again.get("generation") != meta.get("generation"):
            return _CHANGED
        return Entry(
            name=name, layer=layer, account=meta.get("account", ""),
            path=data_path, index_path=index_path,
            epoch=epoch, age=age, data=data, count=_count(data), hit=True,
        )

    def _load(self, path: Path):
        try:
            # свой файл читается напрямую: кэш пишет этот же слой, и путь к
            # нему он строит сам. Испорченная запись здесь не отказ, а
            # промах — данные перечитываются у Директа.
            return json.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return None
        except (OSError, UnicodeDecodeError, ValueError) as exc:
            self.warn(
                f"Запись кэша {short(path)} не прочиталась ({excerpt(exc, 120)}) "
                f"и считается отсутствующей. Данные будут запрошены заново."
            )
            return None

    # -- запись -------------------------------------------------------------

    def write(self, name: str, layer: str, data, *, index=None, signature=None,
              since=None):
        """Положить данные в кэш и вернуть запись.

        Возвращает `Entry` и в режиме `store=False` — просто без путей: у
        вызывающего кода один путь исполнения, а не два.

        `since` — метки отзыва, снятые до похода за данными (см. `_marks`).
        Если к моменту записи они сменились, значит запись успели отозвать или
        кэш очистить, и класть туда добытое раньше нельзя: это вернуло бы
        данные «до» на весь срок жизни слоя. Такая выгрузка отдаётся
        вызывающему коду, но в кэш не попадает."""
        _ttl(layer, None)
        entry = Entry(
            name=name, layer=layer, account=self.account, path=None, index_path=None,
            epoch=self.clock(), age=0.0, data=data, count=_count(data), hit=False,
        )
        if not self.store:
            return entry

        index_text = index(data) if callable(index) else index
        if index_text is not None and not isinstance(index_text, str):
            raise DirectFailure(
                f"Индекс записи «{excerpt(name, 64)}» — не текст, а "
                f"{type(index_text).__name__}. TSV собирается функцией `tsv`."
            )
        meta = {
            "name": name,
            "layer": layer,
            "account": self.account,
            # Метка поколения. Отличать поколения по времени записи нельзя:
            # часы бывают грубыми, а в проверках они и вовсе стоят на месте —
            # две записи получают одну отметку, и перепроверка чтения такую
            # смену не видит. Случайная метка уникальна независимо от часов.
            "generation": os.urandom(8).hex(),
            "epoch": entry.epoch,
            "stored_at": time.strftime("%Y-%m-%dT%H:%M:%S%z", time.localtime(entry.epoch)),
            "count": entry.count,
            "signature": signature,
        }
        # Индент, а не самая компактная запись: по этому файлу будут искать
        # через `grep`, и однострочный JSON на мегабайт отдаёт весь мегабайт
        # одной строкой — ровно то контекстное окно, ради которого всё это.
        # ensure_ascii=False по той же причине: `grep Ромашка` должен находить.
        body = _dumps(data, indent=2)
        meta_body = _dumps(meta, indent=2)
        # Метаданные проверяются наравне с данными: подпись запроса приходит
        # снаружи, и запрос, подписанный вместе с токеном, лёг бы на диск в
        # файле, который проверку содержимого не проходил вовсе.
        self._guard(name, (data, meta), body, index_text, meta_body)

        data_path = self.path(name)
        meta_path = self.path(name, META_SUFFIX)
        data_path.parent.mkdir(parents=True, exist_ok=True)
        # Под замками: три файла заменяются по одному, и два процесса без них
        # перемешивают поколения устойчиво — чужой JSON под своим индексом.
        # Разделяемый на кэш держит от очистки, исключительный на запись — от
        # второго пишущего. Порядок взятия — см. `_exclusive`.
        index_path = None
        lock_path = self.path(name, LOCK_SUFFIX)
        with _exclusive(self.root / WIPE_LOCK, warn=self.warn, shared=True), \
                _exclusive(lock_path, warn=self.warn):
            if since is not None and self._marks(name) != since:
                # Запись отозвали, пока мы ходили за данными. Сказать надо
                # вслух: молчаливый пропуск выглядит как попадание в кэш,
                # которого не случилось, и следующий вызов идёт в сеть снова.
                self.warn(
                    f"Запись «{name}» отозвана, пока читались данные. В кэш "
                    f"они не попадут: это данные до отзыва."
                )
                return entry
            # Прежние метаданные снимаются до первой правки файлов. Пока их
            # нет, записи для `read` не существует — а значит, оборвавшаяся
            # перезапись даёт промах, а не смесь: новые данные под прежней
            # отметкой времени, прежним числом объектов и, если оборвало между
            # ними, прежним индексом. Промах стоит одного вызова API, смесь —
            # неверного ответа.
            _unlink(meta_path)
            _replace(data_path, body)
            if index_text is not None:
                index_path = self.path(name, ".tsv")
                _replace(index_path,
                         index_text if index_text.endswith("\n") else index_text + "\n")
            else:
                # Прежний индекс удаляется вместе с прежними данными.
                # Оставленный, он находится при чтении и выдаётся за индекс
                # новой выгрузки — `grep` уверенно показывает объекты, которых
                # там уже нет.
                _unlink(self.path(name, ".tsv"))
            # Метаданные последними — это и есть точка фиксации: до неё записи
            # нет, после неё она целиком новая.
            _replace(meta_path, meta_body)
            # Метка меняется и на удачной записи, не только на отзыве. Иначе
            # две выгрузки, начатые вместе, кладутся в порядке возвращения:
            # ушедшая раньше приходит позже и затирает более свежую, делая
            # старый снимок свежим на весь срок жизни слоя.
            _restamp(lock_path)

        entry.path = data_path
        entry.index_path = index_path
        return entry

    def through(self, name: str, layer: str, produce, *, index=None, ttl=None,
                signature=None):
        """Кэш-первым: сохранённое, а если его нет — то, что вернёт `produce`.

        Это и есть «повторный вызов читающего скрипта не делает сетевого
        запроса»: сеть живёт внутри `produce`, и второй раз он не зовётся.

        Двум процессам, промахнувшимся об одну запись **разом**, этого мало:
        замки стоят на записи, а не на походе за данными, и `produce` зовёт
        каждый. Слои из `SINGLE_FLIGHT` от этого избавлены — см. `_sole`;
        остальные ходят за данными как ходили, вне замков.

        Не дождавшийся чужого похода возвращается сюда и идёт обычным путём.
        Ждать второй раз, уже на замке записи, ему не приходится: замок этот
        берётся на время правки файлов, а не на время сетевого вызова."""
        found = self.read(name, layer, ttl=ttl)
        if found is not None:
            return found
        # Ждать чужого похода имеет смысл только там, где чужую запись возьмут.
        # При `--no-cache` (`reuse=False`) сохранённое не берут по просьбе
        # человека, и очередь в сеть выстроилась бы ради данных, которые всё
        # равно будут прочитаны заново.
        wait = SINGLE_FLIGHT.get(layer) if self.reuse and self.store else None
        if wait is not None:
            found = self._sole(name, layer, produce, index=index, ttl=ttl,
                               signature=signature, wait=wait)
            # `None` — не дождались чужой записи. Дальше общим путём: лишний
            # вызов стоит балла, а зависшая команда — всей сессии.
            if found is not None:
                return found
        # Метки отзыва снимаются до похода за данными, а сверяются при записи.
        # Между этими двумя моментами конвейер записи успевает изменить кабинет
        # и отозвать запись — и тогда добытое здесь уже описывает прошлое.
        since = self._marks(name) if self.store else None
        return self.write(name, layer, produce(), index=index,
                          signature=signature, since=since)

    def _sole(self, name: str, layer: str, produce, *, index, ttl, signature,
              wait: float):
        """Один поход за данными на всех промахнувшихся. `None` — не дождались.

        Первый пришедший занимает замок похода и только потом перечитывает
        кэш. Остальные видят замок занятым и ждут не его, а саму запись:
        появившаяся отвечает на тот же вопрос, ради которого стояли, и стоит
        ноль баллов. Одного без другого не хватает: замок без второй проверки
        только выстраивает очередь в сеть, а вторая проверка без замка застаёт
        запись ещё не сделанной.

        Замок здесь **свой**, не тот, под которым идёт запись, и это не
        удвоение. Замок записи, взятый через сетевой вызов, держал бы секунды
        всех: соседнюю запись, отзыв после конвейера, очистку кэша, — а сеть
        вынесена из-под замков именно затем, чтобы этого не было. Замок похода
        не держит никого, кроме следующего идущего за теми же данными, и
        `write` берёт свои замки как всегда, на время правки трёх файлов.

        Ожидание ограничено `wait`. Сосед, упавший между замком и записью, не
        должен останавливать команду навсегда, и не дождавшийся идёт за
        данными сам — обычным путём, никого не дожидаясь.

        Очистка кэша сносит файл замка похода вместе с остальными, и двое
        промахнувшихся посреди неё снова идут вдвоём. Это цена, а не изъян:
        удержать файл значило бы держать очистку, а от неверной записи в этом
        случае защищают метки отзыва — их `write` сверяет и здесь."""
        flight_path = self.path(name, FLIGHT_SUFFIX)
        # Часы монотонные, а не `self.clock`: тот показывает время записи и в
        # проверках стоит на месте, а предел ожидания, отмеряемый стоящими
        # часами, не наступает никогда.
        deadline = time.monotonic() + wait
        while True:
            with _attempted(flight_path, warn=self.warn) as taken:
                if taken:
                    # Вторая проверка кэша — под замком: пока стояли в
                    # очереди, сосед мог успеть записать всё целиком.
                    found = self.read(name, layer, ttl=ttl)
                    if found is not None:
                        return found
                    since = self._marks(name)
                    return self.write(name, layer, produce(), index=index,
                                      signature=signature, since=since)
            # Замок занят: за данными уже пошли. Ждём не замка, а записи.
            found = self.read(name, layer, ttl=ttl)
            if found is not None:
                return found
            if time.monotonic() >= deadline:
                return None
            time.sleep(SINGLE_FLIGHT_POLL)

    def _marks(self, name: str) -> tuple:
        """Метки отзыва: у самой записи и у кэша целиком.

        Две, потому что отзывов тоже два. `forget(name)` меняет метку записи,
        а очистка кабинета или всего кэша сносит файлы замков вместе с их
        метками — и уцелеть может только метка в корне, которую очистка не
        трогает. Сверять одну запись значило бы не заметить очистку."""
        return (_stamp(self.path(name, LOCK_SUFFIX)), _stamp(self.root / WIPE_LOCK))

    def _guard(self, name: str, objects, *texts) -> None:
        """Отказать, если в кэш едет секрет.

        Две проверки, потому что каждая по отдельности дырява. По тексту —
        вырезание знает только те токены, которые кто-то зарегистрировал через
        `keep_secret`; в процессе, который до кэша не читал настройки, список
        пуст. По именам ключей — ловит `Authorization` и `Password` независимо
        от того, знаком ли скиллу их значение.

        Проверяется и индекс: он собирается из тех же данных, но отдельной
        функцией, и «в JSON чисто» про TSV ничего не говорит. И метаданные: в
        них лежит подпись запроса, а её составляет вызывающий код.

        Само значение в сообщении не показывается: жалоба на утечку секрета,
        печатающая секрет, — это утечка секрета."""
        for text in texts:
            if text is not None and redact(text) != text:
                raise DirectFailure(
                    f"В запись кэша «{excerpt(name, 64)}» попал токен. "
                    f"Кэш такого не хранит: уберите поле из данных до записи."
                )
        found = _forbidden_key(objects)
        if found:
            raise DirectFailure(
                f"В запись кэша «{excerpt(name, 64)}» попало поле «{found}» — "
                f"по имени это учётные данные. Кэш такого не хранит: уберите "
                f"поле из данных до записи."
            )

    # -- очистка ------------------------------------------------------------

    def forget(self, name=None, *, everything: bool = False) -> int:
        """Объявить сохранённое недействительным. Возвращает число удалённых файлов.

        У кэша без кабинета такая область — весь кэш вместе со всеми
        кабинетами, поэтому она требует `everything=True`. Кэш без кабинета
        заводится не ради очистки, а ради общих записей вроде перечня
        кабинетов, и промах в имени не должен стоить содержимого соседей."""
        if name is not None:
            removed = 0
            # Под теми же замками, что и запись: снятие трёх файлов вперемешку
            # с чужой перезаписью оставило бы от неё половину. Сам файл замка
            # не снимается — он и есть то, на чём держится очередь.
            lock_path = self.path(name, LOCK_SUFFIX)
            with _exclusive(self.root / WIPE_LOCK, warn=self.warn, shared=True), \
                    _exclusive(lock_path, warn=self.warn):
                for suffix in (".json", ".tsv", META_SUFFIX):
                    removed += _unlink(self.path(name, suffix))
                # Метка отзыва меняется здесь же: выгрузка, начатая до отзыва,
                # иначе вернётся и положит в кэш данные «до» — с новой отметкой
                # времени и на весь срок жизни слоя. Отзыв, который можно
                # отменить задним числом, отзывом не является.
                _restamp(lock_path)
            return removed
        if not self.folder and not everything:
            raise DirectFailure(
                "Кэш не привязан к кабинету, и очистка задела бы все кабинеты "
                "сразу. Если это и требуется — forget(everything=True)."
            )
        # Исключительный замок на кэш: очистка сносит и файлы замков записей,
        # в том числе занятый. Тот, кто его держит, остался бы с удалённым
        # файлом, следующий пишущий завёл бы новый, и два пишущих пошли бы
        # одновременно. Пишущие берут этот же замок разделяемым, поэтому
        # очистка ждёт, пока они закончат, и начинается на пустом месте.
        wipe_lock = self.root / WIPE_LOCK
        with _exclusive(wipe_lock, warn=self.warn):
            removed = _wipe(self.directory, self.root)
            # Метки отзыва лежали в файлах замков и ушли вместе с ними, а
            # выгрузка, начатая до очистки, вернётся и положит в кэш данные
            # «до». Поэтому очистка отмечается здесь — в файле, который её
            # переживает. Одной метки на весь кэш хватает: очистка касается
            # всех записей сразу, и различать их незачем.
            _restamp(wipe_lock)
            if self.folder and self.directory.is_dir():
                # Каталог кабинета удаляется вместе с содержимым: пустой
                # каталог в перечне выглядит как кабинет, у которого кэш есть,
                # но пуст. Корень кэша так не удаляется — его держит в git
                # `.gitkeep`.
                #
                # Внутри замка, а не после него: снаружи пишущий успевает
                # дождаться своей очереди и завести каталог заново, а это
                # удаление сносит его между `mkdir` и первым файлом — и запись
                # падает на пропавшем родителе.
                try:
                    self.directory.rmdir()
                except OSError:
                    pass
        return removed

    def entries(self) -> list:
        """Что лежит в кэше: по записям метаданных, без чтения самих данных.

        У кэша без кабинета обходится весь корень — это перечень по всем
        кабинетам сразу, каким его показывает `scripts/cache.py`."""
        found = [
            _describe(path, self.root, self.clock())
            for path in self.directory.rglob("*" + META_SUFFIX)
            # Подменённые ссылкой метаданные не разворачиваются: перечень
            # показал бы поля чужого кабинета как свои. Чтение это уже
            # различает, а перечень ходит своим путём, мимо `path`.
            if path.is_file() and not path.is_symlink()
        ]
        return sorted(found, key=lambda row: (row["folder"], row["name"]))


class Entry:
    """Одна запись кэша — прочитанная или только что положенная.

    `data` — снимок: одно поколение, прочитанное целиком. На нём и работают.

    `path` и `index_path` — **имена**, а не снимки: они указывают на текущее
    поколение, каким бы оно ни стало к моменту, когда файл откроют. Это не
    недосмотр, а то, ради чего путь и печатается: человек открывает его через
    минуту после сводки и должен увидеть кэш таким, какой он сейчас. Сузить
    здесь нечего — окно расхождения начинается там, где чтение заканчивается, а
    неизменное имя поколения (`campaigns.a1b2c3.json`) отняло бы у пути ровно
    то свойство, ради которого он есть.

    Кому нужны данные, совпадающие с файлом байт в байт, тот берёт `data`:
    они уже в памяти и перечитывания не требуют."""

    __slots__ = ("name", "layer", "account", "path", "index_path", "epoch",
                 "age", "data", "count", "hit")

    def __init__(self, **values):
        for field in self.__slots__:
            setattr(self, field, values[field])

    @property
    def stored(self) -> bool:
        """Легли ли полные данные в файл. Ложь в режиме чтения мимо кэша."""
        return self.path is not None

    def __repr__(self) -> str:
        where = f"{self.account}/{self.name}" if self.account else self.name
        return (
            f"<Entry {where} {self.layer} "
            f"{'из кэша' if self.hit else 'свежая'} объектов={self.count}>"
        )


