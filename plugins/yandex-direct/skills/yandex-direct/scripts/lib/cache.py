def _dumps(value, indent=None) -> str:
    # allow_nan=False: NaN и Infinity стандартный JSON не разбирает, и запись
    # с ними — файл, который прочитает только Python. Отказ здесь честнее.
    try:
        return json.dumps(value, ensure_ascii=False, indent=indent, allow_nan=False,
                          sort_keys=False, default=str)
    except ValueError as exc:
        raise DirectFailure(
            f"Данные не сериализуются в JSON: {excerpt(exc, 120)}. "
            f"В кэш кладётся то, что вернул Директ, а не объекты Python."
        ) from None


def _replace(path: Path, text: str) -> None:
    """Запись целиком или никак.

    Через временный файл рядом и `os.replace`: прерванная запись оставила бы
    обрезанный JSON, а он читается как «кэш есть» и отдаёт половину выгрузки
    за целую."""
    temporary = path.with_name(path.name + f".tmp{os.getpid()}")
    try:
        temporary.write_text(text, encoding="utf-8")
        os.replace(temporary, path)
    except OSError as exc:
        _unlink(temporary)
        raise DirectFailure(
            f"Не удалось записать {short(path)}: {exc}"
        ) from None


def _unlink(path: Path) -> int:
    try:
        path.unlink()
        return 1
    except FileNotFoundError:
        return 0
    except OSError as exc:
        raise DirectFailure(f"Не удалось удалить {short(path)}: {exc}") from None


def _inside(path: Path, root: Path) -> bool:
    """Лежит ли путь внутри корня кэша.

    Оба пути разворачиваются одинаково — `realpath` снимает и `..`, и
    символьные ссылки. Одинаково это важнее, чем полно: временный каталог на
    macOS лежит за ссылкой `/var` → `/private/var`, и развёрнутый корень рядом
    с неразвёрнутым путём объявил бы свой же файл чужим.

    `realpath` годится и для того, чего ещё нет: несуществующий хвост он просто
    нормализует. Существующая же часть разворачивается по-настоящему, и ссылка
    в середине пути перестаёт быть способом увести очистку в чужой каталог."""
    real_root = Path(os.path.realpath(root))
    target = Path(os.path.realpath(path))
    return target == real_root or real_root in target.parents


def _no_links(path: Path, root: Path) -> None:
    """Ни сам файл, ни каталоги на пути к нему не должны быть ссылками.

    Ссылка, ведущая наружу, отсекается проверкой принадлежности корню. Ссылка,
    ведущая внутрь него же, — нет: `cache/псевдоним` → `cache/настоящий`
    остаётся под корнем, и запись через неё ложится в файлы чужого кабинета.
    Кабинеты при этом смешиваются ровно так, как раскладка обещает не
    допускать, — только незаметно, потому что имена разные.

    Файл проверяется наравне с каталогами: подменённый ссылкой `campaigns.json`
    отдаётся вместе с чужими данными под свои метаданные и свой индекс, и
    сверка поколения этого не видит — метаданные-то свои.

    Проверяется и при чтении: читать по псевдониму, а писать в оригинал —
    разница, которую заметят не сразу."""
    stop = Path(os.path.normpath(root.absolute()))
    probe = path
    while True:
        current = Path(os.path.normpath(probe.absolute()))
        if current == stop or current == current.parent:
            return
        if probe.is_symlink():
            raise DirectFailure(
                f"{short(probe)} — символьная ссылка. Каталог кэша ссылкой "
                f"быть не может: через неё два кабинета делят одни файлы."
            )
        probe = probe.parent


def _existing(path: Path):
    return path if path.is_file() else None


def _stamp(path: Path) -> str:
    """Метка отзыва записи: содержимое её файла замка.

    Читается без замка — до похода за данными, — поэтому может застать запись
    на середине. Разорванное чтение отличается от целого, а это ровно то, что
    и требуется: «метка не та» означает «пока ходили, запись отозвали»."""
    try:
        # свой файл читается напрямую: это метка в файле замка, которую
        # кладёт сам слой.
        return path.read_text(encoding="utf-8", errors="replace")[:64]
    except OSError:
        return ""


def _restamp(path: Path) -> None:
    """Сменить метку отзыва. Только под замком этого же файла.

    Пишется на месте, а не через временный файл с переименованием: замена
    подменила бы inode, и тот, кто держит замок, держал бы его на файле,
    которого больше нет в каталоге."""
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        # `a+`, а не `r+`: на платформе без замков файла может не быть вовсе,
        # и отзыв не должен падать из-за того, что его никто не создал.
        # свой файл читается напрямую: файл замка заводит и переписывает
        # сам слой, чужого содержимого в нём не бывает.
        with path.open("a+", encoding="utf-8") as handle:
            handle.seek(0)
            handle.write(os.urandom(8).hex())
            handle.truncate()
    except OSError:
        # Метку сменить не удалось — отзыв от этого не отменяется, но
        # запоздалая выгрузка его переживёт. Молчать об этом нельзя.
        raise DirectFailure(
            f"Не удалось отметить отзыв записи в {short(path)}. Выгрузка, "
            f"начатая до отзыва, может вернуть в кэш прежние данные."
        ) from None


@contextlib.contextmanager
def _exclusive(path: Path, warn=None, shared: bool = False):
    """Правку одной записи кэша делает один процесс за раз.

    Запись состоит из трёх файлов, и заменяются они по одному. Два процесса,
    промахнувшихся мимо одной записи и пошедших за данными, без замка
    перемешают поколения устойчиво: один успевает заменить данные, второй —
    все три файла, первый дописывает индекс и метаданные. Получается чужой JSON
    под своим индексом, и перепроверка на стороне чтения такую смесь не видит —
    она собрана до чтения и выглядит целой.

    Замок берётся на отдельном пустом файле и снимается закрытием — то есть и
    при падении процесса. Файла-замка, который надо снимать руками после сбоя,
    здесь нет намеренно: заклинивший кэш хуже перемешанного.

    `shared=True` — разделяемый замок: им пишущие берут `WIPE_LOCK`, чтобы не
    мешать друг другу, но не дать очистке снести файлы прямо под собой.

    Порядок взятия всегда один: сначала разделяемый на кэш, потом
    исключительный на запись. Обратный порядок где-нибудь ещё дал бы взаимную
    блокировку, и это единственное, о чём здесь надо помнить.

    Ждать под замком дорого только в теории: сеть живёт в `through` снаружи, а
    внутри остаётся запись трёх файлов. Так и у слоёв с одиночным походом: там
    сеть накрыта своим замком (`_sole`, `FLIGHT_SUFFIX`), а этот по-прежнему
    берётся на время правки файлов и ни на что больше."""
    if fcntl is None:  # не POSIX
        yield
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = None
    try:
        # свой файл читается напрямую: файл замка открывается ради самого
        # замка, содержимое отсюда не читается вовсе.
        handle = path.open("a+")
        fcntl.flock(handle.fileno(), fcntl.LOCK_SH if shared else fcntl.LOCK_EX)
    except OSError as exc:
        # Файловая система без замков — сетевая, например. Работать без замка
        # хуже, чем с ним, но лучше, чем не работать; молчать об этом нельзя.
        if handle is not None:
            handle.close()
        if warn is not None:
            warn(
                f"Замок на {short(path)} не ставится ({excerpt(exc, 80)}). "
                f"Запись идёт без него: одновременная правка этой же записи "
                f"другим процессом перемешает поколения."
            )
        yield
        return
    try:
        yield
    finally:
        handle.close()


@contextlib.contextmanager
def _attempted(path: Path, warn=None):
    """Попытка взять исключительный замок, не вставая в очередь.

    Отдаёт `True`, если замок взят, и `False`, если он занят другим процессом.
    Этим `_sole` и отличает первого пришедшего от ждущих: вставший в очередь
    узнал бы о чужом походе только тогда, когда тот уже кончился.

    Замка нет вовсе — не POSIX или файловая система без замков — значит нет и
    очереди: отдаётся `True`, и одиночный поход вырождается в обычный. Каждый
    идёт за данными сам, как ходил до всякого `SINGLE_FLIGHT`."""
    if fcntl is None:  # не POSIX
        yield True
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = None
    try:
        # свой файл читается напрямую: файл замка открывается ради самого
        # замка, содержимое отсюда не читается вовсе.
        handle = path.open("a+")
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        # Занят соседом — это не отказ, а ответ. Ловится до `OSError`: он ей
        # родитель, и общая ветка приняла бы занятый замок за сломанный.
        handle.close()
        yield False
        return
    except OSError as exc:
        if handle is not None:
            handle.close()
        if warn is not None:
            warn(
                f"Замок на {short(path)} не ставится ({excerpt(exc, 80)}). "
                f"Данные будут запрошены без него: соседний процесс, "
                f"промахнувшийся об эту же запись, запросит их тоже."
            )
        yield True
        return
    try:
        yield True
    finally:
        handle.close()


def _wipe(directory: Path, root: Path) -> int:
    """Удалить содержимое каталога внутри кэша, сохранив `.gitkeep`.

    Удаляется содержимое, а не сам каталог: `skills/yandex-direct/cache/`
    отслеживается git через `.gitkeep`, и снос корня делает рабочее дерево
    грязным. Символьная ссылка не разворачивается — удаляется сама ссылка,
    иначе очистка кэша вычистила бы то, на что она указывает."""
    # Корень здесь не разрешается: разрешить один путь из двух значит сравнить
    # `/var/...` с `/private/var/...` и объявить свой же каталог чужим.
    # Нормализацией обоих занимается `_inside`.
    if not _inside(directory, root):
        raise DirectFailure(
            f"Очистка {short(directory)} отменена: путь ведёт за пределы "
            f"{short(root)}."
        )
    if directory.is_symlink() and directory != root:
        # Каталог кабинета оказался ссылкой на другой каталог. Пойти по ней
        # значит вычистить чужой кабинет и оставить саму ссылку — то есть
        # удалить не то, что просили. Снимается псевдоним, как и вложенные
        # ссылки ниже. Корень так не снимается: его мог увести в другое место
        # сам пользователь, и это его право.
        return _unlink(directory)
    if not directory.is_dir():
        return 0
    removed = 0
    for item in sorted(directory.iterdir()):
        # `.gitkeep` держит каталог в git, `.wipe.lock` — очередь пишущих.
        # Удалить второй значит начать удалять из-под тех, кого он ждёт.
        if item.name in (KEEP_FILE, WIPE_LOCK):
            continue
        if item.is_dir() and not item.is_symlink():
            removed += sum(1 for nested in item.rglob("*") if nested.is_file())
            try:
                shutil.rmtree(item)
            except OSError as exc:
                raise DirectFailure(
                    f"Не удалось удалить {short(item)}: {exc}"
                ) from None
        else:
            removed += _unlink(item)
    return removed


def _describe(meta_path: Path, root: Path, now: float) -> dict:
    """Одна строка перечня кэша: кабинет, имя, слой, возраст, размер.

    Битая запись метаданных не пропускается: место она всё равно занимает, и
    перечень, который её не показывает, — это перечень, по которому непонятно,
    откуда взялись мегабайты. Незаполненные поля остаются пустыми."""
    try:
        # свой файл читается напрямую: метаданные записи кладёт сам слой.
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, ValueError):
        meta = {}
    if not isinstance(meta, dict):
        meta = {}
    relative = meta_path.relative_to(root)
    folder = relative.parts[0] if len(relative.parts) > 1 else ""
    if folder.startswith("."):
        # Каталог общих записей кабинетом не является и выбран быть не может:
        # `Cache(".sync")` отвергается. Показать его в графе кабинета значит
        # назвать кабинетом то, чего в перечне кабинетов никогда не будет.
        # Сам каталог при этом виден — он входит в имя записи.
        folder = ""
    stem = str(meta_path)[: -len(META_SUFFIX)]
    data_path = Path(stem + ".json")
    index_path = Path(stem + ".tsv")
    # Через ту же воронку, что и чтение: перечень заводится, чтобы показывать
    # в том числе испорченные записи, и падать на их отметке времени ему
    # особенно нечего. Возраст, которого нет, так и остаётся неизвестным.
    epoch = _finite(meta.get("epoch"))
    return {
        # Через ту же чистку, что и печать: одиночный суррогат `json.loads`
        # принимает, а `print` на нём падает — и перечень, заведённый ради
        # показа испорченных записей, отказывал бы именно на них.
        "folder": _printable(folder),
        "name": _printable(meta.get("name") or data_path.stem),
        "layer": _printable(meta.get("layer") or "?"),
        "age": None if epoch is None else max(0.0, now - epoch),
        "size": _size(data_path) + _size(index_path),
        # Число объектов — тоже из файла, и тоже через воронку: `NaN` в нём
        # роняет машиночитаемый вывод на `allow_nan=False`, а перечень заведён
        # ровно затем, чтобы испорченную запись показать, а не свалиться на ней.
        "count": _counted(meta.get("count")),
        "path": data_path,
        "index_path": _existing(index_path),
    }


def _counted(value):
    """Число объектов из файла: целое и неотрицательное, иначе неизвестно."""
    number = _finite(value)
    if number is None or number < 0 or number != int(number):
        return None
    return int(number)


def _size(path: Path) -> int:
    try:
        return path.stat().st_size
    except OSError:
        return 0


def _count(data) -> int:
    if isinstance(data, (list, tuple)):
        return len(data)
    if isinstance(data, dict):
        return len(data)
    return 1


def _finite(value):
    """Число из чужих рук или `None`. `NaN` и бесконечности числами не считает.

    Одна воронка на все числа, приходящие снаружи: отметку времени из файла,
    срок жизни из места вызова. `json.loads` принимает `NaN` за число, а
    сравнения с ним все ложны — возраст выходит `NaN`, и просроченная запись
    оказывается вечно свежей. Это не промах, а обратное промаху: данные,
    которые никогда не перечитают. То же значение, пришедшее сроком жизни,
    делает вечной любую запись, а `-Infinity` в перечне кэша роняет подсчёт
    возраста.

    Логическое значение числом тоже не считается: `True` в поле времени — это
    испорченный файл, а не единица."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    try:
        return value if math.isfinite(value) else None
    except OverflowError:
        # Целое в Python неограниченной длины, и `1` с четырьмя сотнями нулей
        # в файле — законный JSON. В float оно не переводится: переполняется и
        # сама проверка, и любое вычитание после неё.
        return None


def _ttl(layer: str, ttl):
    """Срок жизни записи: слой, явное переопределение или `FOREVER`."""
    if layer not in LAYERS:
        raise DirectFailure(
            f"Неизвестный слой кэша «{excerpt(layer, 32)}». "
            f"Допустимо: {', '.join(LAYERS)}"
        )
    if LAYERS[layer] is FOREVER:
        if ttl is not None:
            # Иначе слой без срока получает срок в месте вызова, и «устаревает
            # по команде» превращается в «устаревает по времени, о котором
            # знает один вызывающий». Не переиспользовать сохранённое — это
            # `--no-cache` (`Cache.from_args`), убрать его — `forget`.
            raise DirectFailure(
                f"Слою «{layer}» срок жизни не задаётся: его записи устаревают "
                f"по явной команде, а не по времени. Не брать сохранённое — "
                f"`--no-cache`, убрать его — forget()."
            )
        return FOREVER
    if ttl is None:
        return LAYERS[layer]
    if _finite(ttl) is None or ttl < 0:
        raise DirectFailure(
            f"Срок жизни записи «{excerpt(ttl, 32)}» — не число секунд."
        )
    return ttl


def _forbidden_key(value, path: str = ""):
    """Первое имя ключа, похожее на учётные данные, или `None`."""
    if isinstance(value, dict):
        for key, nested in value.items():
            name = KEY_NOISE.sub("", str(key).lower())
            if name in FORBIDDEN_KEYS:
                return f"{path}{key}" if path else str(key)
            found = _forbidden_key(nested, f"{path}{key}.")
            if found:
                return found
    elif isinstance(value, (list, tuple)):
        for index, nested in enumerate(value):
            found = _forbidden_key(nested, f"{path}{index}.")
            if found:
                return found
    return None
