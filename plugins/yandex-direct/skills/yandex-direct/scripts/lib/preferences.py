def warn_to_stderr(text: str) -> None:
    """Единственный путь предупреждений записи: stderr, секреты вырезаны."""
    print(redact(text), file=sys.stderr)


def _now() -> str:
    """Отметка времени со смещением зоны.

    Смещение не украшение: запись переживает и задачу, и машину, а «когда я на
    это соглашался» — вопрос, который задают именно к ней. Время без зоны
    читается как местное читающего, а не пишущего."""
    return time.strftime("%Y-%m-%dT%H:%M:%S%z", time.localtime())


@contextlib.contextmanager
def _exclusive(path: Path, warn=None):
    """Правку записи делает один процесс за раз.

    Правка здесь — это «прочитать, изменить одно значение, записать целиком»,
    и без замка два процесса теряют одно из двух значений устойчиво: оба
    прочитали старое, второй записал поверх первого. Потерянным оказывается
    согласие человека, и выглядит потеря как несохранившийся ответ.

    Под тем же замком идёт и чтение — из-за увода испорченной записи в
    `.broken`. Это единственное место, где чтение пишет, и без общего замка оно
    успевало бы увести файл, который соседний процесс только что записал целым.

    Замок не берётся у кэша: тот держит поколение записи из трёх файлов и
    очередь к очистке целого каталога, здесь же один файл и одна операция.
    Общего у них только `fcntl`.

    Снимается замок закрытием файла, то есть и при падении процесса: файла,
    который надо снимать руками после сбоя, здесь нет намеренно."""
    if fcntl is None:  # не POSIX
        yield
        return
    handle = None
    try:
        # Каталог заводится здесь же, внутри `try`: на каталоге скилла,
        # открытом только на чтение, `mkdir` поднимает `PermissionError` —
        # это `OSError`, и он обязан стать предупреждением, а не трассировкой
        # посреди чтения. Отказ по существу придёт от записи, которой есть что
        # сказать про непишущийся каталог.
        path.parent.mkdir(parents=True, exist_ok=True)
        # свой файл читается напрямую: файл замка открывается ради самого
        # замка, содержимое отсюда не читается вовсе.
        handle = path.open("a+")
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
    except OSError as exc:
        # Файловая система без замков — сетевая, например. Работать без замка
        # хуже, чем с ним, но лучше, чем не работать; молчать об этом нельзя.
        if handle is not None:
            handle.close()
        if warn is not None:
            warn(
                f"Замок на {short(path)} не ставится ({excerpt(exc, 80)}). "
                f"Правка идёт без него: одновременная правка этой же записи "
                f"другим процессом потеряет одно из двух значений."
            )
        yield
        return
    try:
        yield
    finally:
        handle.close()


class Preferences:
    """Выбор, запомненный для одного кабинета.

    Одна запись — один файл `settings/<логин кабинета>.json`:

        {
          "schema": 1,
          "account": "api-artwist-test",
          "values": {
            "utm_scheme": {"value": "utm_source=ya&…", "at": "2026-09-01T12:00:00+0300"}
          }
        }

    Логин лежит внутри в том виде, в каком его дал вызывающий код: имя файла
    приведено к нижнему регистру, потому что файловая система macOS по
    умолчанию регистронезависима и `Romashka` с `romashka` — один файл.

    Отметка времени у каждого значения, а не у файла: «когда я на это
    соглашался» спрашивают про конкретный выбор, а общая на запись отвечала бы
    временем последней правки любого из четырёх."""

    def __init__(self, account: str, *, root=SETTINGS_DIR, warn=None):
        if not account:
            # Запись принадлежит кабинету, и кабинет без имени означал бы одну
            # общую запись на все: выбор, сделанный для одного, применился бы
            # ко всем остальным молча.
            raise DirectFailure(
                "Настройки принадлежат кабинету, а логин не задан. Кабинет "
                "берётся из --account или из Accounts.current()."
            )
        # Имя файла проверяется тем же, чем имя каталога кэша и журнала: `../`
        # в логине уводит запись за пределы каталога, а токен, набранный в
        # `--account`, стал бы именем файла — секретом на диске мимо всякой
        # проверки содержимого. Сообщение об отказе говорит «в кэше»: проверка
        # общая, и требование к имени у всех трёх каталогов одно.
        self.account = account
        self.name = cache_module.account_dir_name(account)
        self.root = Path(root)
        self.warn = warn or warn_to_stderr

    def __repr__(self) -> str:
        return f"<Preferences {self.account}>"

    # -- пути ---------------------------------------------------------------

    @property
    def path(self) -> Path:
        return self.root / (self.name + ".json")

    @property
    def lock_path(self) -> Path:
        return self.root / (self.name + ".json" + LOCK_SUFFIX)

    # -- чтение -------------------------------------------------------------

    def recall(self, key: str):
        """Запомненное значение или `None`, если записи нет.

        `None` означает ровно «записи нет»: умолчание берёт правило, которому
        ключ принадлежит, и оно же называет человеку разницу. Испорченная и
        пустая запись отвечают так же — правилу нужен ответ, а не отказ
        команды из-за файла, который перезапишет следующее согласие."""
        record = self._values().get(_known(key))
        return None if record is None else record["value"]

    def remembered(self) -> dict:
        """Всё запомненное для кабинета: `{ключ: значение}`.

        То, что показывают человеку, когда он спрашивает, что скилл про этот
        кабинет помнит. Ключи здесь только знакомые: незнакомый в записи
        остаётся, но толковать его эта версия не берётся."""
        return {key: record["value"] for key, record in self._values().items()}

    def remembered_at(self, key: str):
        """Когда значение запомнили, строкой со смещением зоны.

        `None` — записи нет; пустая строка — запись есть, а времени в ней не
        разобралось. Различать их стоит: первое означает «не спрашивали», а
        второе — «спрашивали, но когда именно, файл больше не говорит»."""
        record = self._values().get(_known(key))
        return None if record is None else record["at"]

    # -- запись -------------------------------------------------------------

    def remember(self, key: str, value, *, agreed: bool) -> bool:
        """Запомнить выбор. Пишет **только** при `agreed=True`.

        Возвращает, **изменилась ли запись**. У `forget` тот же ответ и тот же
        смысл: отказ запомнить — обычный ход разговора, а не сбой, и
        вызывающему коду он нужен, чтобы не говорить «запомнил» там, где не
        запомнил. Различать «человек отказался» и «менять было нечего» по
        ответу не нужно: `agreed` вызывающий код передал сам.

        `agreed` — согласие **запомнить**, а не согласие применить выбор к
        текущей задаче. Правила `NAME-07`, `EXT-04` и `UTM-02` спрашивают
        отдельно, и второе первым не покрывается."""
        key = _known(key)
        _agreement(agreed, key)
        if value is None:
            # «Записи нет» и «записано пусто» стали бы неотличимы, и снятый
            # выбор навсегда превратился бы в «больше не спрашивай». Отказ
            # приходит и при `agreed=False`: пустое значение — ошибка формы, а
            # не ответ человека, и молчать о ней на одном из двух путей значит
            # ловить её через раз.
            raise DirectFailure(
                f"Выбор «{key}» нельзя запомнить пустым: `None` в этой записи "
                f"означает «записи нет». Снимается выбор через forget()."
            )
        wrong = _wrong_shape(key, value)
        if wrong is not None:
            raise DirectFailure(
                f"Выбор «{key}» ({KEYS[key][0]}) — {KEYS[key][1]}, и "
                f"{wrong}. Ответ человека разбирает вызывающий код: «нет» — "
                f"это False, а не строка «нет»."
            )
        if not agreed:
            return False
        with _exclusive(self.lock_path, warn=self.warn):
            raw = self._raw()
            raw[key] = {"value": value, "at": _now()}
            self._store(raw)
        return True

    def forget(self, key: str, *, agreed: bool) -> bool:
        """Снять запомненное. Снимает **только** при `agreed=True`.

        Возвращает, **изменилась ли запись** — как и `remember`. Согласие
        требуется то же, что и на запись: снятое молча выглядит для человека
        так же, как несохранённое, и различить их снаружи нечем.

        Нужно это `S-06`: после удавшегося перехода на шаблон разметки
        запомненное «оставить схему кабинета» обязано уйти, иначе оно вернёт
        прежнюю схему первой же новой кампанией — кабинет разъедется заново, и
        руками самого скилла."""
        key = _known(key)
        _agreement(agreed, key)
        if not agreed:
            return False
        with _exclusive(self.lock_path, warn=self.warn):
            raw = self._raw()
            if key not in raw:
                return False
            del raw[key]
            self._store(raw)
        return True

    # -- содержимое ---------------------------------------------------------

    def _values(self) -> dict:
        """Разобранные значения знакомых ключей: `{ключ: {value, at}}`.

        Незнакомый ключ и значение неожиданной формы пропускаются с
        предупреждением: одно испорченное значение не делает нечитаемыми
        остальные. Кэш в такой ситуации отвергает запись целиком и перечитывает
        её у Директа; здесь перечитывать неоткуда, и терять три ответа человека
        из-за четвёртого не за что.

        Замок берётся, только если файл есть. Иначе чтение у кабинета, про
        который ничего не запомнено, заводило бы каталог настроек и файл замка
        в нём — мусор на ровном месте, а таких чтений большинство."""
        try:
            # Проба через `stat`, а не через `exists()`. Разница не в стиле:
            # `exists()` отвечает «нет» на любой отказ, и отличается это по
            # версиям. На 3.12 он поднимает `PermissionError` на каталоге без
            # права входа, на 3.14 — возвращает `False` (замер 01.09.2026,
            # 3.12.12 и 3.14.2), а `ENOTDIR` съедают обе. Заголовок скрипта
            # допускает и ту, и другую.
            #
            # Съеденный отказ хуже отказа: запомненный выбор есть, а правило
            # берёт умолчание и молчит — человек видит, что скилл спрашивает
            # заново, и не узнаёт почему. `stat` различает «файла нет» и «не
            # достучались» одинаково на всех версиях.
            try:
                self.path.stat()
            except FileNotFoundError:
                return {}
            with _exclusive(self.lock_path, warn=self.warn):
                raw = self._raw()
        except DirectFailure as failure:
            # Запись непонятна, и сохранить её не удалось. Чтению это не повод
            # ронять команду: правило возьмёт умолчание, а файл останется на
            # месте — трогать его нельзя, пока копии нет.
            self.warn(f"{failure} Правила возьмут умолчания.")
            return {}
        except (OSError, ValueError, RecursionError, UnicodeDecodeError) as exc:
            # Сеть, ловящая враждебный файл и враждебное окружение целиком.
            # Внутренние ветки уводят запись там, где это возможно, — но
            # чтению нельзя падать и там, где невозможно: `Path.exists()`
            # поднимает `PermissionError` на каталоге без права входа, разбор
            # — `RecursionError` на глубокой вложенности. Правило обязано
            # получить умолчание, а не трассировку.
            #
            # Перечень узкий намеренно: ошибки самого кода — `TypeError`,
            # `AttributeError` — сюда не попадают и остаются видимыми.
            self.warn(
                f"Настройки {short(self.path)} не прочитались "
                f"({excerpt(exc, 120)}). Правила возьмут умолчания."
            )
            return {}
        found = {}
        for key, record in raw.items():
            if key not in KEYS:
                self.warn(
                    f"{short(self.path)}: ключ «{excerpt(key, 64)}» этой версии "
                    f"скилла незнаком и пропущен. В записи он останется."
                )
                continue
            if (not isinstance(record, dict) or "value" not in record
                    or record["value"] is None):
                self.warn(
                    f"{short(self.path)}: значение «{key}» записано непонятно "
                    f"и считается отсутствующим. Правило {KEYS[key][0]} возьмёт "
                    f"своё умолчание."
                )
                continue
            wrong = _wrong_shape(key, record["value"])
            if wrong is not None:
                # Не отказ и не догадка о том, что имелось в виду: строка
                # «false» под отказом от промоакции истинна, и понять её как
                # «нет» значило бы решить за человека. Правило спросит заново.
                self.warn(
                    f"{short(self.path)}: значение «{key}» не той формы — "
                    f"{wrong}. Считается отсутствующим, правило {KEYS[key][0]} "
                    f"возьмёт своё умолчание."
                )
                continue
            found[key] = {"value": record["value"],
                          "at": _stamped(record.get("at"))}
        return found

    def _raw(self) -> dict:
        """Значения записи как они лежат на диске, без разбора формы.

        Зовётся под замком: непонятую запись эта ветка уводит в `.broken`.

        Сырыми — чтобы правка одного значения не выбрасывала соседние: ключ
        незнакомый или испорченный переживёт запись соседа и достанется той
        версии, которая его поймёт."""
        try:
            # свой файл читается напрямую: запись пишет этот же класс, и путь
            # к ней он строит сам.
            text = self.path.read_text(encoding="utf-8")
        except FileNotFoundError:
            return {}
        except (OSError, UnicodeDecodeError) as exc:
            # Уводим, а не оставляем на месте. Прежняя редакция рассуждала так:
            # «файл не открылся, и переименование не откроется тоже» — и это
            # неверно дважды. Переименование не требует права **читать** файл,
            # только права писать в каталог; а битые байты открываются и
            # читаются, не разбирается только их UTF-8.
            #
            # Цена ошибки — вся запись целиком: непрочитанное считалось пустым,
            # и следующее согласие клало на его место одно новое значение,
            # уничтожая все прежние ответы человека без копии. Если увести не
            # выйдет, не выйдет и запись: у обоих одно условие — право писать
            # в каталог.
            return self._set_aside(f"она не прочиталась ({excerpt(exc, 80)})")
        try:
            stored = json.loads(text)
        except (ValueError, RecursionError) as exc:
            # `RecursionError` — не `ValueError`, и сотня тысяч вложенных
            # массивов в двухсоткилобайтном файле роняла чтение трассировкой.
            # Разбор чужого файла обязан кончаться уводом, а не падением.
            return self._set_aside(f"не разбирается как JSON ({excerpt(exc, 80)})")
        if not isinstance(stored, dict):
            return self._set_aside("это не объект JSON")
        try:
            # Той же проверкой, что и запись, — буквально тем же вызовом.
            # Прочитать то, что нельзя записать, ломается дважды: запись
            # читается, но не переписывается — правка соседнего значения
            # падает на сериализации, — и читается неверно: `NaN` под
            # отказом от промоакции истинен, а токен уезжает в параметры
            # URL кампании.
            _encoded(stored)
        except DirectFailure as failure:
            return self._set_aside(f"её нельзя записать обратно — {failure}")
        schema = stored.get("schema")
        # Тип наравне со значением. Python считает `True` и `1.0` равными
        # единице, и запись с `"schema": true` прошла бы как своя — номер схемы
        # перестал бы делать то единственное, ради чего он здесь. `bool`
        # отсекается отдельно: он подкласс `int`.
        if isinstance(schema, bool) or not isinstance(schema, int) \
                or schema != SCHEMA:
            return self._set_aside(
                f"записана схемой {excerpt(stored.get('schema'), 32)}, "
                f"а эта версия скилла понимает схему {SCHEMA}"
            )
        owner = stored.get("account")
        if not isinstance(owner, str) or _folder(owner) != self.name:
            # Имя файла — логин, но файл переносят: восстановление из копии,
            # синхронизация каталога, копия «на всякий случай» руками. Запись,
            # легшая под чужой логин, отдала бы соседнему кабинету чужую схему
            # разметки и чужой формат имени — то самое «кабинет получит две
            # схемы от самого скилла», против чего написан `UTM-02`.
            #
            # Поле в записи есть с самого начала, и читать его обязательно:
            # записанное и никем не читаемое значение не проверяет ничего, а
            # выглядит проверкой.
            return self._set_aside(
                f"она записана для кабинета «{excerpt(owner, 64)}», а читают её "
                f"для «{self.account}»"
            )
        values = stored.get("values")
        if not isinstance(values, dict):
            return self._set_aside("в ней нет объекта «values»")
        return values

    def _aside(self):
        """Свободное имя для увода или `None`, если свободного нет.

        Имя ищется свободное, а не берётся одно и то же: увод существует ради
        сохранности, а увод поверх прежнего её и уничтожает. Случай не
        выдуманный — так ведёт себя откат версии после подъёма схемы. Старая
        версия не понимает запись новой, уводит её и заводит свою; новая,
        вернувшись, не понимает уже эту — и вторым уводом легла бы на
        единственную копию ответов, которые собиралась переносить."""
        base = self.path.with_name(self.path.name + BROKEN_SUFFIX)
        if _free(base):
            return base
        for number in range(2, ASIDE_LIMIT + 1):
            candidate = base.with_name(f"{base.name}.{number}")
            if _free(candidate):
                return candidate
        return None

    def _set_aside(self, why: str) -> dict:
        """Увести непонятую запись рядом и вернуть пустые значения.

        Не удаление: ответ человека ничем не воспроизводится, и «не
        прочиталось — начнём с чистого листа» стирало бы согласие молча.

        **Не уведя, отказывает.** Прежняя редакция предупреждала, что файл
        перезапишет «следующее согласие», и это было неверно: зовут этот путь
        из `remember`, и следующее согласие — то самое, которое сейчас и
        выполняется. Пустой ответ уходил в слияние, новое значение ложилось в
        него одно, и единственная копия записи исчезала в том же вызове.

        Отсюда разделение ролей: чтение вправе выродиться в умолчание правила и
        ловит этот отказ у себя, а запись поверх несохранённого не идёт вовсе."""
        aside = self._aside()
        if aside is None:
            # Сотня уведённых записей под одним кабинетом — это сотня
            # непрочитанных предупреждений. Но перезаписать поверх них нельзя:
            # исчезнет то, чего никто не видел.
            raise DirectFailure(
                f"Настройки {short(self.path)}: {why}, и уводить некуда — "
                f"рядом уже {ASIDE_LIMIT} уведённых записей. Запись не идёт: "
                f"разберите уведённое руками."
            )
        try:
            os.replace(self.path, aside)
        except OSError as exc:
            raise DirectFailure(
                f"Настройки {short(self.path)}: {why}, и увести их в "
                f"{short(aside)} не удалось ({excerpt(exc, 80)}). Запись не "
                f"идёт: она легла бы поверх несохранённого."
            ) from None
        self.warn(
            f"Настройки {short(self.path)}: {why}. Файл уведён в "
            f"{short(aside)}, правила возьмут умолчания."
        )
        return {}

    def _store(self, values: dict) -> None:
        """Запись целиком или никак. Зовётся под замком.

        Через временный файл рядом и `os.replace`: прерванная запись оставила
        бы обрезанный JSON, а он читается как порча — то есть уводится в
        `.broken` вместе с ответами человека, которые в нём уцелели."""
        body = {"schema": SCHEMA, "account": self.account, "values": values}
        try:
            encoded = _encoded(body)
        except DirectFailure as failure:
            raise DirectFailure(f"Выбор для {self.account} {failure}") from None
        try:
            self.root.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            # Каталог настроек заводится при первой записи, и завестись он
            # может не всегда: каталог скилла бывает открыт только на
            # чтение. Отказ обязан прийти отказом скилла — человеку
            # показывают то, что поймано, а трассировка из недр `mkdir`
            # доходит до него поломкой самого скилла.
            raise DirectFailure(
                f"Каталог настроек {short(self.root)} не заводится: {exc}. "
                f"Запомнить выбор не удалось — правило спросит снова."
            ) from None
        temporary = self.path.with_name(self.path.name + f".tmp{os.getpid()}")
        try:
            temporary.write_bytes(encoded)
            os.replace(temporary, self.path)
        except OSError as exc:
            try:
                temporary.unlink()
            except OSError:
                pass
            raise DirectFailure(
                f"Настройки {short(self.path)} не пишутся: {exc}. Запомнить "
                f"выбор не удалось — правило спросит снова."
            ) from None


def _encoded(body) -> bytes:
    """Байты записи — или отказ, если записать её нельзя.

    Единственное место, где решается записываемость, и зовут его **обе**
    стороны: запись перед файлом и разбор перед тем, как отдать прочитанное
    правилу. Так закрыт класс, а не случай.

    Класс этот ревью нашло трижды подряд, по случаю за круг: `NaN` и
    бесконечности, одинокий суррогат, токен в значении. Каждый раз чтение
    принимало то, что запись отвергает, и каждый раз чинить следующий случай
    значило ждать четвёртого. Здесь проверки перечислены один раз, и правило
    «читается тем же, чем пишется» держится устройством, а не памятью: новая
    проверка, добавленная записи, применяется к чтению сама.

    Кодирование входит в проверку наравне с сериализацией: одинокий суррогат
    лежит в файле обычным ASCII, становится суррогатом после снятия
    экранирования, сериализуется молча и падает только на UTF-8. Делается оно
    **до** первого файла: `write_text` к моменту отказа успевает завести пустой
    временный.

    `ensure_ascii=False` обязателен и не для красоты: с умолчательным `True`
    суррогат уезжает обратно в экранированный вид, кодирование проходит, и
    проверка пропускает ровно то, ради чего заведена. «Тем же правилом» значит
    теми же аргументами."""
    try:
        # allow_nan=False: NaN и Infinity стандартный JSON не разбирает, и
        # запись с ними прочитает только Python.
        text = json.dumps(body, ensure_ascii=False, indent=2, allow_nan=False)
        data = text.encode("utf-8")
    except (TypeError, ValueError, UnicodeEncodeError, RecursionError) as exc:
        raise DirectFailure(
            f"не записывается: {excerpt(exc, 120)}. Здесь лежит ответ "
            f"человека — не объекты Python, не бесконечности и не одинокие "
            f"суррогаты."
        ) from None
    if redact(text) != text:
        # Тем же правилом, что у кэша: значение приходит из разговора, и токен,
        # набранный человеком в ответ на вопрос о схеме разметки, лёг бы на
        # диск — а оттуда в параметры URL кампании. Само значение не
        # показывается: жалоба на утечку, печатающая секрет, и есть утечка.
        raise DirectFailure(
            "в ней токен. Настройки такого не хранят: уберите его из значения."
        )
    return data


def _wrong_shape(key: str, value):
    """Чем значение не подходит своему ключу, или `None`, если подходит.

    Одна проверка на запись и на чтение, потому что вход один и тот же ответ
    человека: в запись он попадает от вызывающего кода, а обратно приходит из
    файла, который могли восстановить или поправить руками. Разные правила по
    двум сторонам означали бы, что записать нельзя, а прочитать можно, — а это
    и есть та поломка, из-за которой `NaN` читался как «да»."""
    wanted = KEYS[key][2]
    # `bool` — подкласс `int`, и проверять его надо раньше и точнее: единица
    # прошла бы как «да», а это уже догадка о том, что человек имел в виду.
    if wanted is bool:
        return None if isinstance(value, bool) else "это не «да» и не «нет»"
    if isinstance(value, bool) or not isinstance(value, wanted):
        return f"это не {wanted.__name__}"
    if wanted is str and _breaking(value):
        return "в нём управляющие символы"
    if wanted is str and not value.strip():
        # Пустая строка — третья форма пустоты рядом с «записи нет» и `None`.
        # Схемой она не бывает ни у одного из правил, а читается как ответ:
        # записанная в `TrackingParams`, она стирает разметку кабинета.
        return "это пустая строка, а не выбор"
    return None


def _free(path) -> bool:
    """Свободно ли имя под увод. Занято — всё, что не «файла нет».

    Пробуется `stat`, а не `exists()`, и по той же причине, по какой проба
    самой записи: `exists()` отвечает «нет» на любой отказ, и отличается это по
    версиям — на 3.14 он глотает и `PermissionError`, и разовый `EIO`. Занятое
    имя, показанное свободным, уводится **поверх** уже сохранённой копии, то
    есть ровно там, где увод обязан её беречь.

    Недостучались — считаем занятым. Ошибка в эту сторону стоит отказа записи,
    в обратную — уничтоженного ответа человека."""
    try:
        path.stat()
    except FileNotFoundError:
        return True
    except OSError:
        return False
    return False


def _breaking(text: str) -> bool:
    """Есть ли в строке символы, которым в выводе делать нечего."""
    return any(unicodedata.category(character) in BREAKING for character in text)


def _stamped(at) -> str:
    """Отметка времени, если она ею является, иначе пустая строка.

    Разбирается тем же форматом, каким пишется. Строка проверяется, а не
    принимается за отметку по одному лишь типу: «вчера» в восстановленной
    руками записи вернулось бы из `remembered_at` как время согласия, а
    `ESC[2J` внутри — стёр бы человеку экран, когда это время покажут.

    Пустая строка — «запись есть, а времени в ней не разобралось»: случай уже
    описан, и негодная отметка попадает именно в него, а не в отдельный."""
    if not isinstance(at, str):
        return ""
    try:
        # `datetime`, а не `time`: последний принимает невозможные смещения
        # зоны — `+2400`, `+2500`, `+9959`, `-2400` проходят у него на обеих
        # версиях (замер 01.09.2026 на 3.12.12 и 3.14.2), и `+2400` вернулось
        # бы из `remembered_at` как время согласия.
        moment = datetime.strptime(at, STAMP)
    except ValueError:
        return ""
    # И обратно тем же форматом. Разбор шире записи даже у `datetime`: `Z` и
    # `+03:00` он принимает, а `_now` таких не пишет — отметка годна ровно
    # тогда, когда она в точности то, что записал бы `_now` в тот момент.
    return at if moment.strftime(STAMP) == at else ""


def _folder(account: str):
    """Имя файла, которым звался бы этот логин, или `None`, если он негоден.

    Сравнивать логины напрямую нельзя: имя файла приведено к нижнему регистру,
    и `Romashka` с `romashka` — один кабинет. А негодный логин внутри записи —
    это порча содержимого, а не отказ команды: `account_dir_name` на нём
    поднимает отказ, и здесь он гасится в «не совпало»."""
    try:
        return cache_module.account_dir_name(account)
    except DirectFailure:
        return None


def _known(key: str) -> str:
    """Ключ из закрытого перечня. Незнакомый — отказ.

    Опечатка иначе пишется в запись и не читается оттуда никогда: `recall`
    отвечает «записи нет», правило берёт умолчание и спрашивает заново, а
    выглядит это как несохранившееся согласие. Молчание здесь неотличимо от
    поломки, ради которой модуль и заведён."""
    if key in KEYS:
        return key
    known = ", ".join(f"{name} ({owner})"
                      for name, (owner, _, _) in sorted(KEYS.items()))
    raise DirectFailure(
        f"«{excerpt(key, 64)}» — не выбор, запоминаемый для кабинета. Здесь "
        f"живут: {known}. Новый ключ заводит карточка-потребитель — строкой в "
        f"KEYS вместе с правилом, которому он принадлежит."
    )


def _agreement(agreed, key: str) -> None:
    """Согласие — это `bool`, а не «что-нибудь истинное».

    Самая вероятная ошибка вызывающего кода — передать сюда сырой ответ
    человека: `bool("нет")` — это `True`, и правило, которое запоминает только
    с согласия, начало бы запоминать отказы."""
    if not isinstance(agreed, bool):
        raise DirectFailure(
            f"Согласие запомнить «{key}» задано значением "
            f"{type(agreed).__name__}, а не True или False. Ответ человека "
            f"разбирает вызывающий код: «нет» — истинная строка."
        )
